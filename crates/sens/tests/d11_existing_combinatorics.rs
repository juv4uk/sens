//! D11: чинні SENS-композиції комбінаторики й оборотного представлення сусідів.
//! Реальне обчислення робить eval_program; Rust лише порівнює спостережений результат.
use sens::{eval_program, load_core_library, Session};
fn law(src: &str, tests: &[(&str, &str)]) {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("D11-COMB-CORE");
    eval_program(src, &mut session).expect("D11-COMB-LOAD");
    for (form, expected) in tests {
        let actual = eval_program(form, &mut session).unwrap_or_else(|error| panic!("D11-COMB input={} expected={} error={}", form, expected, error)).value.to_string();
        assert_eq!(actual, *expected, "D11-COMB input={} expected={} actual={}", form, expected, actual);
    }
}

#[test]
fn d11_subsets_native_laws() {
    law(include_str!("../../../lib/list-all-subsets-by-position-general.lisp"), &[
        ("(усі-підмножини-за-позиціями (як-є ()))", "(())"),
        ("(усі-підмножини-за-позиціями (як-є (а)))", "(() (а))"),
        ("(усі-підмножини-за-позиціями (як-є (а б)))", "(() (б) (а) (а б))"),
        ("(усі-підмножини-за-позиціями (як-є (а а)))", "(() (а) (а) (а а))"),
    ]);
}

