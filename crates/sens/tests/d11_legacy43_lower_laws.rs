//! Предметні SENS-свідки чинних D1/D3/D4/D6/D8 законів, зіставлених
//! із нератифікованими 43 історичними тестовими написами D11.
//! Тільки реальний eval_program SENS визначає результат; Rust звіряє D1.
//! Це НЕ допуск 11-бітних кодів до виклику та НЕ ратифікація.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_legacy43_existing_pure_lower_domain_laws_are_native() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинний SENS Core");
    // D10 IF має ратифіковану адресу, але не має тут доведеного callable-механізму.
    // Ліниве розгалуження перевіряємо чинним D3 COND у реальному SENS, без підміни D10.
    for (id, source, expected) in [
        ("д1-так", r#"так"#, true),
        ("д1-ні", r#"ні"#, false),
        ("д4-заперечити-ні", r#"(хибне? ні)"#, true),
        ("д4-заперечити-так", r#"(хибне? так)"#, false),
        ("д8-рівні-вкладені", r#"(однакові? (як-є (а (б))) (як-є (а (б))))"#, true),
        ("д8-нерівні-вкладені", r#"(однакові? (як-є (а (б))) (як-є (а б)))"#, false),
        ("д8-рівні-порожні", r#"(однакові? (як-є ()) (як-є ()))"#, true),
        ("д8-порожній-не-список", r#"(однакові? (як-є ()) (як-є (а)))"#, false),
        ("д8-та-без-аргументів", r#"(та)"#, true),
        ("д8-або-без-аргументів", r#"(або)"#, false),
        ("д8-та-істина", r#"(та так так)"#, true),
        ("д8-та-хиба", r#"(та так ні)"#, false),
        ("д8-або-істина", r#"(або ні так)"#, true),
        ("д8-або-хиба", r#"(або ні ні)"#, false),
        ("д8-та-не-обчислювати-хвіст", r#"(та ні (перше так))"#, false),
        ("д8-або-не-обчислювати-хвіст", r#"(або так (перше так))"#, true),
        ("д3-умова-істина", r#"(за-умовою (так (атом? (як-є а))) ((атом? (як-є ())) (перше (як-є ()))))"#, true),
        ("д3-умова-хиба", r#"(за-умовою (ні (перше (як-є ()))) ((атом? (як-є ())) (атом? (як-є а))))"#, true),
        ("д3-умова-пропустити-хвіст", r#"(за-умовою (так (атом? (як-є (а)))) ((атом? (як-є ())) (перше (як-є ()))))"#, false),
        ("д8-існує-збіг-порожній", r#"(існує-збіг? (функція (х) (атом? х)) (як-є ()))"#, false),
        ("д8-існує-збіг-присутній", r#"(існує-збіг? (функція (х) (атом? х)) (як-є ((а) б)))"#, true),
        ("д8-існує-збіг-відсутній", r#"(існує-збіг? (функція (х) (атом? х)) (як-є ((а) (б))))"#, false),
        ("д8-існує-збіг-коротке-виконання", r#"(існує-збіг? (функція (х) (за-умовою ((тотожне? х (як-є небезпека)) (перше (як-є ()))) ((атом? (як-є ())) (тотожне? х (як-є а))))) (як-є (а небезпека)))"#, true),
        ("д6-усі-порожній", r#"(усі? (функція (х) (атом? х)) (як-є ()))"#, true),
        ("д6-усі-атоми", r#"(усі? (функція (х) (атом? х)) (як-є (а б)))"#, true),
        ("д6-усі-є-список", r#"(усі? (функція (х) (атом? х)) (як-є (а (б))))"#, false),
        ("д6-усі-не-обчислювати-після-відмови", r#"(усі? (функція (х) (за-умовою ((тотожне? х (як-є небезпека)) (перше (як-є ()))) ((атом? (як-є ())) (тотожне? х (як-є а))))) (як-є (б небезпека)))"#, false),
    ] {
        let value = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-LEGACY43-{id} layer=SENS input={source} expected=D1:{expected} actual_error={error}"
            )).value;
        assert_eq!(value.as_predicate_bit(), Some(expected),
            "test_id=D11-LEGACY43-{id} layer=SENS input={source} expected=D1:{expected} actual={value}");
    }
}

#[test]
fn d11_legacy43_existing_d24_list_boundaries_are_native() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинний SENS Core");
    for (id, source, expected) in [
        ("д6-довжина-порожніх", r#"(тотожне? (довжина (як-є ())) (довжина (як-є ())))"#, true),
        ("д6-довжина-однакова", r#"(тотожне? (довжина (як-є (а б))) (довжина (як-є (в г))))"#, true),
        ("д6-довжина-різна", r#"(тотожне? (довжина (як-є (а))) (довжина (як-є (а б))))"#, false),
        ("д6-взяти-нуль", r#"(однакові? (взяти 0 (як-є (а б в))) (як-є ()))"#, true),
        ("д6-взяти-один", r#"(однакові? (взяти 1 (як-є (а б в))) (як-є (а)))"#, true),
        ("д6-взяти-понад-довжину", r#"(однакові? (взяти 3 (як-є (а б))) (як-є (а б)))"#, true),
        ("д6-взяти-не-реверс", r#"(однакові? (взяти 2 (як-є (а б в))) (як-є (б а)))"#, false),
        ("д8-підпослідовність-середина", r#"(однакові? (підпослідовність (як-є (а б в г)) 1 3) (як-є (б в)))"#, true),
        ("д8-підпослідовність-порожня-межа", r#"(однакові? (підпослідовність (як-є (а б в)) 1 1) (як-є ()))"#, true),
        ("д8-підпослідовність-не-змінювати-межу", r#"(однакові? (підпослідовність (як-є (а б в)) 1 2) (як-є (в)))"#, false),
        ("д6-відкинути-нуль", r#"(однакові? (відкинути 0 (як-є (а б в))) (як-є (а б в)))"#, true),
        ("д6-відкинути-один", r#"(однакові? (відкинути 1 (як-є (а б в))) (як-є (б в)))"#, true),
        ("д6-відкинути-понад-довжину", r#"(однакові? (відкинути 3 (як-є (а б))) (як-є ()))"#, true),
        ("д6-відкинути-не-залишати-перший", r#"(однакові? (відкинути 1 (як-є (а б))) (як-є (а)))"#, false),
    ] {
        let value = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-LEGACY43-{id} layer=SENS input={source} expected=D1:{expected} actual_error={error}"
            )).value;
        assert_eq!(value.as_predicate_bit(), Some(expected),
            "test_id=D11-LEGACY43-{id} layer=SENS input={source} expected=D1:{expected} actual={value}");
    }
}
