//! Живі закони D11: одномісна версія Clojure juxt на замиканнях SENS.
//! Rust перевіряє біт D1; семантика виконується лише у eval_program SENS.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_clojure_juxt_unary_closures_and_negative_laws_native() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинне ядро SENS");
    eval_program(include_str!("../../../lib/d11-clojure-juxt.lisp"), &mut session)
        .expect("справжні SENS-визначення D11 juxt");

    for (id, program, expected) in [
        ("порожній-набір-атом", r#"(однакові? (застосувати-набір-одномісних-функцій (як-є ()) (як-є а)) (як-є ()))"#, true),
        ("порожній-набір-список", r#"(однакові? (застосувати-набір-одномісних-функцій (як-є ()) (як-є (а б))) (як-є ()))"#, true),
        ("тотожність", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) х)) (як-є а)) (як-є (а)))"#, true),
        ("константа", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (як-є б))) (як-є а)) (як-є (б)))"#, true),
        ("вкладений", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (список х))) (як-є а)) (як-є ((а))))"#, true),
        ("два-виходи", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) х) (функція (х) (список х))) (як-є а)) (як-є (а (а))))"#, true),
        ("перший-та-хвіст", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (перше х)) (функція (х) (решта х))) (як-є (а б в))) (як-є (а (б в))))"#, true),
        ("хвіст-та-перший", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (решта х)) (функція (х) (перше х))) (як-є (а б в))) (як-є ((б в) а)))"#, true),
        ("хвіст-одного", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (перше х)) (функція (х) (решта х))) (як-є (а))) (як-є (а ())))"#, true),
        ("вкладений-вхід", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (перше х)) (функція (х) (решта х))) (як-є ((а) б))) (як-є ((а) (б))))"#, true),
        ("повтор-функції", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) х) (функція (х) х)) (як-є а)) (як-є (а а)))"#, true),
        ("порожнє-значення", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (як-є ())) (функція (х) х)) (як-є а)) (як-є (() а)))"#, true),
        ("подвоєння", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (список х х))) (як-є а)) (як-є ((а а))))"#, true),
        ("лексичне-захоплення", r#"(однакові? ((функція (збережене) (застосувати-набір-одномісних-функцій (список (функція (х) збережене) (функція (х) х)) (як-є б))) (як-є а)) (як-є (а б)))"#, true),
        ("конструктор-порожній", r#"(однакові? ((побудувати-зіставлення-функцій (як-є ())) (як-є а)) (як-є ()))"#, true),
        ("конструктор-один", r#"(однакові? ((побудувати-зіставлення-функцій (список (функція (х) х))) (як-є а)) (як-є (а)))"#, true),
        ("конструктор-два", r#"(однакові? ((побудувати-зіставлення-функцій (список (функція (х) (перше х)) (функція (х) (решта х)))) (як-є (а б))) (як-є (а (б))))"#, true),
        ("конструктор-порожнє", r#"(однакові? ((побудувати-зіставлення-функцій (список (функція (х) (як-є ())) (функція (х) х))) (як-є а)) (як-є (() а)))"#, true),
        ("не-перевернути", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (перше х)) (функція (х) (решта х))) (як-є (а б))) (як-є ((б) а)))"#, false),
        ("не-сплющити", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (список х))) (як-є а)) (як-є (а)))"#, false),
        ("не-відкидати-повтори", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) х) (функція (х) х)) (як-є а)) (як-є (а)))"#, false),
        ("не-відкидати-порожнє", r#"(однакові? (застосувати-набір-одномісних-функцій (список (функція (х) (як-є ())) (функція (х) х)) (як-є а)) (як-є (а)))"#, false),
        ("не-кешувати-вхід", r#"(однакові? ((побудувати-зіставлення-функцій (список (функція (х) х))) (як-є б)) (як-є (а)))"#, false),
        ("не-змінити-порядок", r#"(однакові? ((побудувати-зіставлення-функцій (список (функція (х) х) (функція (х) (список х)))) (як-є а)) (як-є ((а) а)))"#, false),
    ] {
        let value = eval_program(program, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-CLOJURE-JUXT-{id} layer=SENS input={program} expected=D1:{expected} actual_error={error}"
            ))
            .value;
        assert_eq!(
            value.as_predicate_bit(), Some(expected),
            "test_id=D11-CLOJURE-JUXT-{id} layer=SENS input={program} expected=D1:{expected} actual={value}"
        );
    }
}
