//! Д11: дев'ять чинних SENS-композицій зі свідками на реальному обчислювачі.
//! Rust не інтерпретує Lisp і не підміняє D1 чи перевірку розділення.
use sens::{eval_program,load_core_library,Session};
fn witness(src: &str, cases: &[(&str,&str)]) {
 let mut session=Session::bare();
 load_core_library(&mut session).expect("test_id=D11-SEQ-CORE");
 eval_program(src,&mut session).expect("test_id=D11-SEQ-LOAD");
 for (form,expected) in cases {
   let actual=eval_program(form,&mut session).unwrap_or_else(|error|panic!("test_id=D11-SEQ layer=SENS input={form} expected={expected} error={error}")).value.to_string();
   assert_eq!(actual,*expected,"test_id=D11-SEQ layer=SENS input={form} expected={expected} actual={actual}");
 }
}

#[test]
fn d11_take_native() {
 witness(include_str!("../../../lib/list-take-while-atom-general.lisp"),&[
  ("(взяти-поки-атом (як-є ()) (як-є а))","()"),
  ("(взяти-поки-атом (як-є (а а б а)) (як-є а))","(а а)"),
  ("(взяти-поки-атом (як-є (б а)) (як-є а))","()"),
  ("(взяти-поки-атом (як-є (а а)) (як-є а))","(а а)"),
 ]);
}

