//! Scheme SRFI-1 FILTER-MAP: саме SENS виконує тіло й лексичне замикання.
//! Критична відмінність: машинний D1 «ні» ≠ структурне порожнє ().
//! Rust не реалізує filter/map, тільки зчитує точний D1 результат свідка.

