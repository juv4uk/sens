//! Д11: реальні SENS-закони поділу, зсуву і наявних суфіксів.
//! Обчислювач SENS визначає D1, Rust лише порівнює результат.
use sens::{eval_program, load_core_library, Session};

fn witness(library: &str, cases: &[(&str, bool)]) {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("test_id=D11-SPLITS-CORE");
    eval_program(library, &mut session).expect("test_id=D11-SPLITS-LIBRARY");
    for (form, expected) in cases {
        let result = eval_program(form, &mut session)
            .unwrap_or_else(|e| panic!("test_id=D11-SPLITS layer=SENS input={form} expected=D1:{expected} error={e}")).value;
        assert_eq!(result.as_predicate_bit(), Some(*expected),
            "test_id=D11-SPLITS layer=SENS input={form} expected=D1:{expected} actual={result}");
    }
}

#[test]
fn d11_last_split_native() {
    witness(include_str!("../../../lib/list-split-last-occurrence-general.lisp"), &[
        ("(однакові? (поділ-перед-останнім (як-є ()) (як-є а)) (як-є (() ())))", true),
        ("(однакові? (поділ-перед-останнім (як-є (а б)) (як-є г)) (як-є ((а б) ())))", true),
        ("(однакові? (поділ-перед-останнім (як-є (а б а в)) (як-є а)) (як-є ((а б) (а в))))", true),
        ("(однакові? (поділ-перед-останнім (як-є (а б а)) (як-є а)) (як-є ((а б) (а))))", true),
        ("(однакові? (поділ-перед-останнім (як-є (а б а в)) (як-є а)) (як-є (() (а б а в))))", false),
    ]);
}

