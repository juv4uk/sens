//! D11 00001011000 — закон перевірки групи DEFINE-функцій.
//! Виконання та розрізнення помилок належить виключно живому SENS MetaEval;
//! ці бібліотечні свідки не надають прямої машинної D11-викличності.

mod common;

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_перевірка_групи_визначень_розрізняє_повтор_і_канонічні_параметри() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("ядро SENS");
    common::load_meta_evaluator_library(&mut session).expect("живий MetaEval");

    for (case, source, expected) in [
        (
            "порожня-група",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ())) (як-є ()))",
            true,
        ),
        (
            "одна-правильна",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х) х))))) (як-є ()))",
            true,
        ),
        (
            "дві-правильні",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х) х)) (визначити бета (функція (у) у))))) (як-є ()))",
            true,
        ),
        (
            "різні-параметри",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х у) х))))) (як-є ()))",
            true,
        ),
        (
            "повторене-імя",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х х) х))))) (як-є (duplicate-parameter х)))",
            true,
        ),
        (
            "повтор-не-інша-помилка",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х х) х))))) (як-є (canonical-parameter х)))",
            false,
        ),
        (
            "канонічна-форма-як-параметр",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (функція) функція))))) (як-є (canonical-parameter функція)))",
            true,
        ),
        (
            "правильна-перед-помилкою",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х) х)) (визначити бета (функція (у у) у))))) (як-є (duplicate-parameter у)))",
            true,
        ),
        (
            "помилка-перед-правильною",
            "(однакові? (помилка-групи-визначень-лямбди (як-є ((визначити альфа (функція (х х) х)) (визначити бета (функція (у) у))))) (як-є (duplicate-parameter х)))",
            true,
        ),
    ] {
        let result = eval_program(source, &mut session)
            .unwrap_or_else(|error| {
                panic!("test_id=D11-META-GROUP-ERROR-{case} layer=SENS input={source} actual_error={error}")
            })
            .value;
        assert_eq!(
            result.as_predicate_bit(),
            Some(expected),
            "test_id=D11-META-GROUP-ERROR-{case} layer=SENS input={source} expected=D1:{expected} actual={result}"
        );
    }
}
