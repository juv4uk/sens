//! Історичний Scheme SRFI-1: SPAN / BREAK як бібліотечні композиції D11.
//! Виконується реальний SENS над lib/d11-srfi1-span-break.lisp.
//! Rust лише звіряє точний D1; жодного host-перекладу семантики.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_srfi1_span_break_preserve_prefix_suffix_and_short_circuit() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("завантажити чинний Core SENS");
    eval_program(
        include_str!("../../../lib/d11-srfi1-span-break.lisp"),
        &mut session,
    )
    .expect("завантажити справжні бібліотечні визначення SRFI-1 у SENS");

    for (id, program, expected) in [
        ("span-empty-prefix",
         "(однакові? (перше (розділити-поки-умова (функція (х) (атом? х)) (як-є ()))) (як-є ()))", true),
        ("span-empty-suffix",
         "(однакові? (решта (розділити-поки-умова (функція (х) (атом? х)) (як-є ()))) (як-є ()))", true),
        ("span-all-prefix",
         "(однакові? (перше (розділити-поки-умова (функція (х) (атом? х)) (як-є (а б в)))) (як-є (а б в)))", true),
        ("span-all-suffix",
         "(однакові? (решта (розділити-поки-умова (функція (х) (атом? х)) (як-є (а б в)))) (як-є ()))", true),
        ("span-stops-prefix",
         "(однакові? (перше (розділити-поки-умова (функція (х) (тотожне? х (як-є а))) (як-є (а б а)))) (як-є (а)))", true),
        ("span-stops-suffix",
         "(однакові? (решта (розділити-поки-умова (функція (х) (тотожне? х (як-є а))) (як-є (а б а)))) (як-є (б а)))", true),
        ("span-not-partition",
         "(однакові? (перше (розділити-поки-умова (функція (х) (тотожне? х (як-є а))) (як-є (а б а)))) (як-є (а а)))", false),
        ("span-no-match-prefix",
         "(однакові? (перше (розділити-поки-умова (функція (х) (тотожне? х (як-є а))) (як-є (б а)))) (як-є ()))", true),
        ("span-no-match-suffix",
         "(однакові? (решта (розділити-поки-умова (функція (х) (тотожне? х (як-є а))) (як-є (б а)))) (як-є (б а)))", true),
        ("span-compound-stops",
         "(однакові? (решта (розділити-поки-умова (функція (х) (атом? х)) (як-є (а (б) в)))) (як-є ((б) в)))", true),
        ("break-empty-prefix",
         "(однакові? (перше (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є ()))) (як-є ()))", true),
        ("break-empty-suffix",
         "(однакові? (решта (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є ()))) (як-є ()))", true),
        ("break-first-prefix",
         "(однакові? (перше (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (б а)))) (як-є ()))", true),
        ("break-first-suffix",
         "(однакові? (решта (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (б а)))) (як-є (б а)))", true),
        ("break-second-prefix",
         "(однакові? (перше (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (а б а)))) (як-є (а)))", true),
        ("break-second-suffix",
         "(однакові? (решта (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (а б а)))) (як-є (б а)))", true),
        ("break-no-match-prefix",
         "(однакові? (перше (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (а в)))) (як-є (а в)))", true),
        ("break-no-match-suffix",
         "(однакові? (решта (розділити-перед-умовою (функція (х) (тотожне? х (як-є б))) (як-є (а в)))) (як-є ()))", true),
        ("span-do-not-visit-tail",
         "(однакові? (решта (розділити-поки-умова (функція (х) (за-умовою ((тотожне? х (як-є небезпека)) (перше (як-є ()))) ((атом? (як-є ())) (тотожне? х (як-є а))))) (як-є (а б небезпека)))) (як-є (б небезпека)))", true),
        ("break-do-not-visit-tail",
         "(однакові? (решта (розділити-перед-умовою (функція (х) (за-умовою ((тотожне? х (як-є небезпека)) (перше (як-є ()))) ((атом? (як-є ())) (тотожне? х (як-є б))))) (як-є (а б небезпека)))) (як-є (б небезпека)))", true),
    ] {
        let value = eval_program(program, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-SRFI1-{id} layer=SENS input={program} expected=D1:{expected} actual_error={error}"
            ))
            .value;
        assert_eq!(
            value.as_predicate_bit(),
            Some(expected),
            "test_id=D11-SRFI1-{id} layer=SENS input={program} expected=D1:{expected} actual={value}"
        );
    }
}
