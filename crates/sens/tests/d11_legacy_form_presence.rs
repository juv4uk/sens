//! Дійсні SENS-свідки восьми історичних HAS-*; не python/JSON oracles.
//! Дослідна бібліотечна композиція, НЕ ратифікація D11.
use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_legacy_has_forms_are_real_sens_predicates() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинний SENS Core");
    eval_program(include_str!("../../../lib/d11-form-presence.lisp"), &mut session)
        .expect("вісім SENS-предикатів мають визначатися нативно");
    for (id, source, expected) in [
        ("наявне-визначення", r#"(містить-форму-визначити? (як-є ((визначити ім'я (як-є а)) (функція (х) х))))"#, true),
        ("наявна-лямбда", r#"(містить-форму-функція? (як-є ((визначити ім'я (функція (х) х)))))"#, true),
        ("наявна-цитата", r#"(містить-форму-цитування? (як-є ((визначити ім'я (як-є а)))))"#, true),
        ("наявний-cons", r#"(містить-форму-сполучити? (як-є ((функція (х) (сполучити х (як-є ()))))))"#, true),
        ("наявний-car", r#"(містить-форму-перше? (як-є ((функція (х) (перше х)))))"#, true),
        ("наявний-atom", r#"(містить-форму-атом? (як-є ((за-умовою ((атом? (як-є а)) так)))))"#, true),
        ("наявний-eq", r#"(містить-форму-тотожне? (як-є ((за-умовою ((тотожне? а б) так)))))"#, true),
        ("наявний-cond", r#"(містить-форму-умов? (як-є ((за-умовою ((атом? а) так)))))"#, true),
        ("не-читати-цитату", r#"(містить-форму-визначити? (як-є ((як-є (визначити приховане а)))))"#, false),
        ("не-читати-цитований-cons", r#"(містить-форму-сполучити? (як-є ((як-є (сполучити а б)))))"#, false),
        ("сама-цитата-видима", r#"(містить-форму-цитування? (як-є ((як-є (визначити приховане а)))))"#, true),
        ("атом-не-виклик", r#"(містить-форму-визначити? (як-є визначити))"#, false),
        ("порожнє-дерево", r#"(містить-форму-умов? (як-є ()))"#, false),
        ("голова-atom", r#"(містить-форму-атом? (як-є (атом? (як-є а))))"#, true),
        ("дані-не-голова", r#"(містить-форму-перше? (як-є (а перше б)))"#, false),
        ("аргумент-не-голова-вкладено", r#"(містить-форму-перше? (як-є (а (б перше в))))"#, false),
        ("справжній-вкладений-виклик", r#"(містить-форму-перше? (як-є (а (б (перше в)))))"#, true),
        ("відсутня-умова", r#"(містить-форму-умов? (як-є ((функція (х) (перше х)))))"#, false),
        ("вкладена-тотожність", r#"(містить-форму-тотожне? (як-є (а (б (тотожне? х у)))))"#, true),
        ("не-плутати-рівність", r#"(містить-форму-тотожне? (як-є ((однакові? а б))))"#, false),
        ("порожній-HAS-DEFINE", r#"(містить-форму-визначити? (як-є ()))"#, false),
        ("порожній-HAS-LAMBDA", r#"(містить-форму-функція? (як-є ()))"#, false),
        ("порожній-HAS-QUOTE", r#"(містить-форму-цитування? (як-є ()))"#, false),
        ("порожній-HAS-CONS", r#"(містить-форму-сполучити? (як-є ()))"#, false),
        ("порожній-HAS-CAR", r#"(містить-форму-перше? (як-є ()))"#, false),
        ("порожній-HAS-ATOM", r#"(містить-форму-атом? (як-є ()))"#, false),
        ("порожній-HAS-EQ", r#"(містить-форму-тотожне? (як-є ()))"#, false),
        ("порожній-HAS-COND", r#"(містить-форму-умов? (як-є ()))"#, false),
    ] {
        let actual = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-HAS-{id} layer=SENS input={source} expected=D1:{expected} actual_error={error}"
            )).value;
        assert_eq!(actual.as_predicate_bit(), Some(expected),
            "test_id=D11-HAS-{id} layer=SENS input={source} expected=D1:{expected} actual={actual}");
    }
}
