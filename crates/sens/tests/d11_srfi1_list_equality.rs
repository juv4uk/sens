//! Д11: два і довільно багато списків, SRFI-1 list=.
//! Порівнювач і виклики виконує SENS, Rust лише перевіряє D1.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_srfi1_list_equality_sens_laws() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("завантажити ядро SENS");
    eval_program(
        include_str!("../../../lib/d11-srfi1-list-equality.lisp"),
        &mut session,
    )
    .expect("визначити SRFI-1 list= у SENS");

    for (id, program, expected) in [
        ("два-порожні", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ()) (як-є ()))"#, true),
        ("два-однакові", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а б в)) (як-є (а б в)))"#, true),
        ("один", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а)) (як-є (а)))"#, true),
        ("повторений-атом", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а а б)) (як-є (а а б)))"#, true),
        ("вкладені", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є ((а) (б в))) (як-є ((а) (б в))))"#, true),
        ("порожні-вкладені", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є (() ())) (як-є (() ())))"#, true),
        ("за-ключем", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? (перше лівий) (перше правий))) (як-є ((а х) (б у))) (як-є ((а я) (б н))))"#, true),
        ("лівий-коротший", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а)) (як-є (а б)))"#, false),
        ("правий-коротший", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а б)) (як-є (а)))"#, false),
        ("лівий-порожній", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ()) (як-є (а)))"#, false),
        ("правий-порожній", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а)) (як-є ()))"#, false),
        ("порядок", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (а б)) (як-є (б а)))"#, false),
        ("вкладені-не-рівні", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є ((а) (б))) (як-є ((а) (в))))"#, false),
        ("атом-проти-списку", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є (а)) (як-є ((а))))"#, false),
        ("ключ-інший", r#"(списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? (перше лівий) (перше правий))) (як-є ((а х) (б у))) (як-є ((а я) (в н))))"#, false),
        ("без-списків", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ()))"#, true),
        ("без-списків-не-викликати", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (перше (як-є ()))) (як-є ()))"#, true),
        ("один-список", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б))))"#, true),
        ("один-не-викликати", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (перше (як-є ()))) (як-є ((а))))"#, true),
        ("два-порожні-у-ряді", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (() ())))"#, true),
        ("три-порожні", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є (() () ())))"#, true),
        ("три-однакові", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б) (а б) (а б))))"#, true),
        ("пара-складених", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є (((а) (б)) ((а) (б)))))"#, true),
        ("три-з-ключем", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? (перше лівий) (перше правий))) (як-є (((а х) (б у)) ((а я) (б н)) ((а в) (б г)))))"#, true),
        ("третій-інший", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б) (а б) (а в))))"#, false),
        ("другий-інший", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б) (а в) (а б))))"#, false),
        ("останній-коротший", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б) (а б) (а))))"#, false),
        ("перший-коротший", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а) (а б) (а б))))"#, false),
        ("три-порядок", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (тотожне? лівий правий)) (як-є ((а б) (а б) (б а))))"#, false),
        ("вкладений-різний", r#"(усі-списки-рівні-за-порівнянням? (функція (лівий правий) (однакові? лівий правий)) (як-є (((а)) ((а)) ((б)))))"#, false),
    ] {
        let value = eval_program(program, &mut session)
            .unwrap_or_else(|error| {
                panic!(
                    "test_id=D11-LIST-EQUALITY-{id} layer=SENS input={program} expected=D1:{expected} actual_error={error}"
                )
            })
            .value;
        assert_eq!(
            value.as_predicate_bit(),
            Some(expected),
            "test_id=D11-LIST-EQUALITY-{id} layer=SENS input={program} expected=D1:{expected} actual={value}"
        );
    }
}
