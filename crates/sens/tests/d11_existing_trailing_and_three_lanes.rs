//! Д11: чинні SENS-закони кінцевих суфіксів та оборотних трійкових потоків.
//! Rust викликає sens::eval_program, не замінює обчислення SENS власними алгоритмами.
use sens::{eval_program, load_core_library, Session};
fn witness(source: &str, cases: &[(&str,bool)]) {
    let mut session=Session::bare();
    load_core_library(&mut session).expect("test_id=D11-TRIPLE-CORE");
    eval_program(source,&mut session).expect("test_id=D11-TRIPLE-LIBRARY");
    for (form,expected) in cases {
        let actual=eval_program(form,&mut session)
          .unwrap_or_else(|error|panic!("test_id=D11-TRIPLE layer=SENS input={form} expected=D1:{expected} error={error}")).value;
        assert_eq!(actual.as_predicate_bit(),Some(*expected),
          "test_id=D11-TRIPLE layer=SENS input={form} expected=D1:{expected} actual={actual}");
    }
}

