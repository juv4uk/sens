//! D11: реальний закон SENS для вже наявного EXTEND-SUBST.
//! Це бібліотечна композиція, не новий машинний примітив і не прямий D11 opcode.
//! Rust лише завантажує SENS та спостерігає точну D1-відповідь.

use sens::{eval_program, Session};

#[test]
fn d11_розширити_підстановку_зберігає_пари_та_пріоритет() {
    let mut session = Session::default();
    eval_program(include_str!("../../../lib/core.lisp"), &mut session)
        .expect("завантажити чинне ядро SENS");
    eval_program(include_str!("../../../lib/unify.lisp"), &mut session)
        .expect("завантажити справжній SENS-закон підстановки");

    // Джерело, формування пар, структурна рівність та розіменування
    // обчислюються усередині SENS, а не у Rust/Python.
    let cases = [
        (
            "порожній-хвіст",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ())) (як-є ((ключ . значення))))",
            true,
        ),
        (
            "обернена-пара",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ())) (як-є ((значення . ключ))))",
            false,
        ),
        (
            "попередній-запис-збережено",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ((старий . вміст)))) (як-є ((ключ . значення) (старий . вміст))))",
            true,
        ),
        (
            "попередній-запис-не-можна-загубити",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ((старий . вміст)))) (як-є ((ключ . значення))))",
            false,
        ),
        (
            "нове-зв'язування-перше",
            "(уніфікація-рівні? (отримати-значення-з-підстановки (логічна-змінна (як-є х)) (розширити-підстановку (логічна-змінна (як-є х)) (як-є нове) (розширити-підстановку (логічна-змінна (як-є х)) (як-є старе) (як-є ())))) (як-є нове))",
            true,
        ),
        (
            "старе-зв'язування-не-перемагає",
            "(уніфікація-рівні? (отримати-значення-з-підстановки (логічна-змінна (як-є х)) (розширити-підстановку (логічна-змінна (як-є х)) (як-є нове) (розширити-підстановку (логічна-змінна (як-є х)) (як-є старе) (як-є ())))) (як-є старе))",
            false,
        ),
    ];
    for (case, source, expected) in cases {
        let actual = eval_program(source, &mut session)
            .unwrap_or_else(|error| {
                panic!("test_id=D11-EXTEND-SUBST-{case} layer=SENS input={source} actual_error={error}")
            })
            .value;
        assert_eq!(
            actual.as_predicate_bit(),
            Some(expected),
            "test_id=D11-EXTEND-SUBST-{case} layer=SENS input={source} expected=D1:{expected} actual={actual}"
        );
    }
}
