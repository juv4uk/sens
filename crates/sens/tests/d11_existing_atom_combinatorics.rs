//! D11: 10 уже визначених SENS-законів атомів, позицій, пар та вікон.
//! Всі 53 позитивні й негативні D1-свідки обчислює тільки SENS.
use sens::{eval_program, load_core_library, Session};

fn check(src: &str, cases: &[(&str, bool)]) {
    let mut s = Session::bare();
    load_core_library(&mut s).expect("test_id=D11-ATOM-COMBINATORICS-CORE");
    eval_program(src, &mut s).expect("test_id=D11-ATOM-COMBINATORICS-LOAD");
    for (form, expected) in cases {
        let actual = eval_program(form, &mut s).unwrap_or_else(|error| panic!("test_id=D11-ATOM-COMBINATORICS layer=SENS input={form} expected=D1:{expected} actual_error={error}")).value;
        assert_eq!(actual.as_predicate_bit(), Some(*expected), "test_id=D11-ATOM-COMBINATORICS layer=SENS input={form} expected=D1:{expected} actual={actual}");
    }
}

