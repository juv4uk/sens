//! D11: історичний Clojure partition-by у скінченних чистих списках SENS.
//! Алгоритм належить lib/d11-clojure-partition-by.lisp;
//! Rust лише подає свідків справжньому SENS та читає точні D1-біти.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_clojure_consecutive_partition_by_has_real_sens_witnesses() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинне ядро SENS");
    for (path, source) in [
        ("lib/d11-srfi1-span-break.lisp", include_str!("../../../lib/d11-srfi1-span-break.lisp")),
        ("lib/d11-clojure-partition-by.lisp", include_str!("../../../lib/d11-clojure-partition-by.lisp")),
    ] {
        eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!("test_id=D11-CLOJURE-LOAD layer=SENS path={path} actual_error={error}"));
    }

    // Закон: ключ обчислюється власною SENS-функцією, структурне зіставлення
    // є канонічним однакові?, не Rust-еквівалентністю чи текстовим збігом.
    for (id, source, expected) in [
        ("порожня-серія",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є ())) (як-є ()))", true),
        ("одиничний-атом",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а))) (як-є ((а))))", true),
        ("одна-серія",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а а а))) (як-є ((а а а))))", true),
        ("усі-різні",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а б в))) (як-є ((а) (б) (в))))", true),
        ("дві-серії",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а а б б))) (як-є ((а а) (б б))))", true),
        ("повтор-після-іншої",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а б а))) (як-є ((а) (б) (а))))", true),
        ("три-серії",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а а б б а))) (як-є ((а а) (б б) (а))))", true),
        ("чотири-серії",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а б б в в а))) (як-є ((а) (б б) (в в) (а))))", true),
        ("першу-не-зливати",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а б а))) (як-є ((а а) (б))))", false),
        ("усі-різні-не-зливати",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а б в))) (як-є ((а б в))))", false),
        ("дві-серії-не-розбивати",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а а б б))) (як-є ((а) (а) (б) (б))))", false),
        ("не-переставляти",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (б б а а))) (як-є ((а а) (б б))))", false),
        ("повтор-знову-не-зливати",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є (а а б б а))) (як-є ((а а а) (б б))))", false),
        ("ключ-перша-позиція",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (перше елемент)) (як-є ((а один) (а два) (б три) (а чотири)))) (як-є (((а один) (а два)) ((б три)) ((а чотири)))))", true),
        ("ключ-перша-позиція-не-плутати-значення",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (перше елемент)) (як-є ((а один) (а два) (б три)))) (як-є (((а один)) ((а два)) ((б три)))))", false),
        ("ключ-решта-пари",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (решта елемент)) (як-є ((а спільне) (б спільне) (в інше)))) (як-є (((а спільне) (б спільне)) ((в інше)))))", true),
        ("ключ-решта-пари-не-плутати",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (решта елемент)) (як-є ((а спільне) (б інше)))) (як-є (((а спільне) (б інше)))))", false),
        ("предикат-атомність",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (атом? елемент)) (як-є (а б (в) (г) д))) (як-є ((а б) ((в) (г)) (д))))", true),
        ("предикат-атомність-негатив",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (атом? елемент)) (як-є (а (в) б))) (як-є ((а б) ((в)))))", false),
        ("порожня-структура-ключ",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (перше елемент)) (як-є ((() а) (() б) (в г)))) (як-є (((( ) а) (() б)) ((в г)))))", true),
        ("складений-ключ",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) (решта елемент)) (як-є ((а х у) (б х у) (в х) (г х у)))) (як-є (((а х у) (б х у)) ((в х)) ((г х у)))))", true),
        ("усі-однакові-структури",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є ((а) (а) (а)))) (як-є (((а) (а) (а)))))", true),
        ("різні-структури",
         "(однакові? (групувати-суміжні-за-ключем (функція (елемент) елемент) (як-є ((а) (б) (а)))) (як-є (((а)) ((б)) ((а)))))", true),
    ] {
        let value = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-CLOJURE-{id} layer=SENS input={source} expected=D1:{expected} actual_error={error}"
            ))
            .value;
        assert_eq!(
            value.as_predicate_bit(),
            Some(expected),
            "test_id=D11-CLOJURE-{id} layer=SENS input={source} expected=D1:{expected} actual={value}"
        );
    }
}
