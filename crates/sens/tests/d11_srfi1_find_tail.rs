//! Д11: SRFI-1 FIND-TAIL — пошук першого суфікса справжнім SENS.
//! Значення невдачі — D1 ні, не порожній список.
//! Rust не реалізує пошук, а лише перевіряє результат D1.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_srfi1_find_tail_sens_witnesses() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинне ядро SENS");
    eval_program(
        include_str!("../../../lib/d11-srfi1-find-tail.lisp"),
        &mut session,
    )
    .expect("визначити FIND-TAIL у справжньому SENS");

    for (id, program, expected) in [
        ("порожній", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є а))) (як-є ())) (як-є ні))"#, true),
        ("немає-збігу", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є в))) (як-є (а б))) (як-є ні))"#, true),
        ("один-є", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є а))) (як-є (а))) (як-є (а)))"#, true),
        ("перший", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є а))) (як-є (а б в))) (як-є (а б в)))"#, true),
        ("середній", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є б))) (як-є (а б в))) (як-є (б в)))"#, true),
        ("останній", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є в))) (як-є (а б в))) (як-є (в)))"#, true),
        ("перший-з-повторів", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є а))) (як-є (б а в а))) (як-є (а в а)))"#, true),
        ("зберегти-пізніші-елементи", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є б))) (як-є (а б в б г))) (як-є (б в б г)))"#, true),
        ("складений-елемент", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (однакові? елемент (як-є (а)))) (як-є (б (а) (в)))) (як-є ((а) (в))))"#, true),
        ("за-першим-у-парі", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? (перше елемент) (як-є б))) (як-є ((а х) (б у) (а я)))) (як-є ((б у) (а я))))"#, true),
        ("замикання-ціль", r#"(однакові? ((функція (ціль) (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент ціль)) (як-є (а б в)))) (як-є б)) (як-є (б в)))"#, true),
        ("збіг-на-ні", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (однакові? елемент (як-є ні))) (список (як-є а) (як-є ні) (як-є б))) (список (як-є ні) (як-є б)))"#, true),
        ("ніякої-перевірки-на-порожньому", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (перше (як-є ()))) (як-є ())) (як-є ні))"#, true),
        ("не-цілий-вихід", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є б))) (як-є (а б в))) (як-є (а б в)))"#, false),
        ("не-пропускати-успішний", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є а))) (як-є (б а а))) (як-є (а)))"#, false),
        ("не-фільтрувати-хвіст", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є б))) (як-є (а б в б))) (як-є (б б)))"#, false),
        ("не-порожній-за-невдачі", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є г))) (як-є (а б))) (як-є ()))"#, false),
        ("не-загубити-вкладені", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (однакові? елемент (як-є (а)))) (як-є (б (а) (в)))) (як-є ((а))))"#, false),
        ("не-шукати-пізніший", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (тотожне? елемент (як-є б))) (як-є (а б в б))) (як-є (б)))"#, false),
        ("не-підміняти-ні", r#"(однакові? (знайти-хвіст-за-умовою (функція (елемент) (однакові? елемент (як-є ні))) (список (як-є а) (як-є ні) (як-є б))) (як-є ні))"#, false),
    ] {
        let value = eval_program(program, &mut session)
            .unwrap_or_else(|error| {
                panic!(
                    "test_id=D11-FIND-TAIL-{id} layer=SENS input={program} expected=D1:{expected} actual_error={error}"
                )
            })
            .value;
        assert_eq!(
            value.as_predicate_bit(),
            Some(expected),
            "test_id=D11-FIND-TAIL-{id} layer=SENS input={program} expected=D1:{expected} actual={value}"
        );
    }
}
