//! Д11: сім виконуваних похідних SENS-законів дерев та підпослідовностей.
//! Дерево/списки обчислює лише eval_program; Rust не підмінює CAR/CDR,
//! атомну тотожність, підрахунок чи структурне порівняння.
//! Вхід — скінченні правильні дерева та списки; арифметики хоста немає.

use sens::{eval_program, load_core_library, Session};

fn native(source: &str) -> Session {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинне ядро SENS");
    eval_program(source, &mut session).expect("чинні SENS-визначення");
    session
}

fn truth(session: &mut Session, family: &str, cases: &[(&str, &str, bool)]) {
    for (name, input, expected) in cases {
        let result = eval_program(input, session)
            .unwrap_or_else(|error| panic!(
                "test_id=D11-TREE-{family}-{name} layer=SENS input={input} expected=D1:{expected} actual_error={error}"
            ))
            .value;
        assert_eq!(
            result.as_predicate_bit(), Some(*expected),
            "test_id=D11-TREE-{family}-{name} layer=SENS input={input} expected=D1:{expected} actual={result}"
        );
    }
}

