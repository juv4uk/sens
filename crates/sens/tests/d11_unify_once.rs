//! D11: одноразове розіменування як визначена SENS-композиція, не новий примітив.
//! Відмінність від рекурсивного пройти перевіряє справжній eval_program SENS.

use sens::{eval_program, Session};

#[test]
fn d11_розвязати_один_раз_не_підмінює_рекурсивне_проходження() {
    let mut session = Session::default();
    eval_program(include_str!("../../../lib/core.lisp"), &mut session)
        .expect("завантажити чинне ядро SENS");
    eval_program(include_str!("../../../lib/unify.lisp"), &mut session)
        .expect("завантажити живі правила уніфікації SENS");

    eval_program(
        r#"
        (визначити один-змінний (логічна-змінна (як-є х)))
        (визначити другий-змінний (логічна-змінна (як-є у)))
        (визначити звязування
          (розширити-підстановку один-змінний другий-змінний
            (розширити-підстановку другий-змінний (як-є готово) (як-є ()))))
        "#,
        &mut session,
    )
    .expect("створити два послідовні бібліотечні зв'язування");

    for (case, source, expected) in [
        (
            "один-крок",
            "(розв'язати-один-раз один-змінний звязування)",
            "(var у)",
        ),
        (
            "повне-проходження",
            "(пройти один-змінний звязування)",
            "готово",
        ),
        (
            "атом-не-змінюється",
            "(розв'язати-один-раз (як-є атом) звязування)",
            "атом",
        ),
        (
            "не-знайдено",
            "(розв'язати-один-раз (логічна-змінна (як-є немає)) звязування)",
            "(var немає)",
        ),
    ] {
        let observed = eval_program(source, &mut session)
            .unwrap_or_else(|error| {
                panic!(
                    "test_id=D11-UNIFY-ONCE-{case} layer=SENS source={source} actual_error={error}"
                )
            })
            .value
            .to_string();
        assert_eq!(
            observed, expected,
            "test_id=D11-UNIFY-ONCE-{case} layer=SENS source={source} expected={expected} actual={observed}"
        );
    }
}


// D11: EXTEND-SUBST, чинна SENS-композиція із lib/unify.lisp.
// Шість свідків, включно з трьома негативними: порядок пар та пріоритет.
#[test]
fn d11_розширити_підстановку_зберігає_пари_та_пріоритет() {
    let mut session = Session::default();
    eval_program(include_str!("../../../lib/core.lisp"), &mut session)
        .expect("чинне SENS-ядро");
    eval_program(include_str!("../../../lib/unify.lisp"), &mut session)
        .expect("справжня SENS-уніфікація");

    for (case, source, expected) in [
        (
            "порожній-хвіст",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ())) (як-є ((ключ . значення))))",
            true,
        ),
        (
            "обернена-пара",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ())) (як-є ((значення . ключ))))",
            false,
        ),
        (
            "попередній-запис-збережено",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ((старий . вміст)))) (як-є ((ключ . значення) (старий . вміст))))",
            true,
        ),
        (
            "попередній-запис-не-можна-загубити",
            "(уніфікація-рівні? (розширити-підстановку (як-є ключ) (як-є значення) (як-є ((старий . вміст)))) (як-є ((ключ . значення))))",
            false,
        ),
        (
            "нове-зв'язування-перше",
            "(уніфікація-рівні? (отримати-значення-з-підстановки (логічна-змінна (як-є х)) (розширити-підстановку (логічна-змінна (як-є х)) (як-є нове) (розширити-підстановку (логічна-змінна (як-є х)) (як-є старе) (як-є ())))) (як-є нове))",
            true,
        ),
        (
            "старе-зв'язування-не-перемагає",
            "(уніфікація-рівні? (отримати-значення-з-підстановки (логічна-змінна (як-є х)) (розширити-підстановку (логічна-змінна (як-є х)) (як-є нове) (розширити-підстановку (логічна-змінна (як-є х)) (як-є старе) (як-є ())))) (як-є старе))",
            false,
        ),
    ] {
        let actual = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!("test_id=D11-EXTEND-SUBST-{case} layer=SENS input={source} error={error}"))
            .value;
        assert_eq!(
            actual.as_predicate_bit(),
            Some(expected),
            "test_id=D11-EXTEND-SUBST-{case} layer=SENS input={source} expected=D1:{expected} actual={actual}"
        );
    }
}

// D11: APPLY-SUBST-WALKED. Перевіряємо саме вже визначену SENS-функцію,
// без нового Rust-примітива та без автоматичного допуску D11 opcode.
#[test]
fn d11_застосувати_підстановку_обійдений_працює_рекурсивно() {
    let mut session = Session::default();
    eval_program(include_str!("../../../lib/core.lisp"), &mut session)
        .expect("чинне SENS-ядро");
    eval_program(include_str!("../../../lib/unify.lisp"), &mut session)
        .expect("справжня SENS-уніфікація");
    eval_program(
        "(визначити підстави (розширити-підстановку (логічна-змінна (як-є х)) (як-є заміна) (як-є ())))",
        &mut session,
    ).expect("підстановка створена самою мовою SENS");

    for (case, source, expected) in [
        (
            "атом-незмінний",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є атом) підстави) (як-є атом))",
            true,
        ),
        (
            "атом-не-підмінено",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є атом) підстави) (як-є інше))",
            false,
        ),
        (
            "вкладена-заміна",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є ((var х) г)) підстави) (як-є (заміна г)))",
            true,
        ),
        (
            "неправильна-заміна",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є ((var х) г)) підстави) (як-є (старе г)))",
            false,
        ),
        (
            "крапкова-пара",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є ((var х) . хвіст)) підстави) (як-є (заміна . хвіст)))",
            true,
        ),
        (
            "порожній-список",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є ()) підстави) (як-є ()))",
            true,
        ),
        (
            "невідома-змінна-збереглася",
            "(уніфікація-рівні? (застосувати-підстановку-обійдений (як-є ((var у))) підстави) (як-є ((var у))))",
            true,
        ),
        (
            "старий-терм-незмінний",
            "(уніфікація-рівні? (як-є ((var х) г)) (як-є ((var х) г)))",
            true,
        ),
    ] {
        let actual = eval_program(source, &mut session)
            .unwrap_or_else(|error| panic!("test_id=D11-APPLY-SUBST-WALKED-{case} layer=SENS input={source} error={error}"))
            .value;
        assert_eq!(
            actual.as_predicate_bit(),
            Some(expected),
            "test_id=D11-APPLY-SUBST-WALKED-{case} layer=SENS input={source} expected=D1:{expected} actual={actual}"
        );
    }
}
