//! Д11: Scheme SRFI-1 COUNT (унарна SENS-проєкція).
//! Лише SENS виконує предикат і рахує; Rust перевіряє D1 результатів.

use sens::{eval_program, load_core_library, Session};

#[test]
fn d11_srfi1_unary_count_native_sens() {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("чинний Core SENS");
    eval_program(
        include_str!("../../../lib/d11-srfi1-unary-count.lisp"),
        &mut session,
    )
    .expect("визначити обидва закони count у SENS");

    for (id, program, expected) in [
        ("порожньо", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є ())) (як-є ()))"#, true),
        ("порожньо-без-виклику", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (перше (як-є ()))) (як-є ())) (як-є ()))"#, true),
        ("один-є", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є (а))) (як-є (так)))"#, true),
        ("один-немає", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є (б))) (як-є ()))"#, true),
        ("усі-три", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) так) (як-є (а б в))) (як-є (так так так)))"#, true),
        ("усі-хибні", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) ні) (як-є (а б в))) (як-є ()))"#, true),
        ("несуміжні", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є (а б а в а))) (як-є (так так так)))"#, true),
        ("складений-збіг", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є (а)))) (як-є ((а) (б) (а)))) (як-є (так так)))"#, true),
        ("атом-не-список", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є (а (а) а))) (як-є (так так)))"#, true),
        ("д1-значення", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є ні))) (як-є (так ні так ні))) (як-є (так так)))"#, true),
        ("нуль-не-ні", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є в))) (як-є (а б))) (як-є ні))"#, false),
        ("нуль-не-один", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є в))) (як-є (а б))) (як-є (так)))"#, false),
        ("два-не-три", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є а))) (як-є (а б а))) (як-є (так так так)))"#, false),
        ("складені-не-всі", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є (а)))) (як-є ((а) (б) (а)))) (як-є (так так так)))"#, false),
        ("пари-порожні", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є ()) (як-є ())) (як-є ()))"#, true),
        ("пари-ліворуч-порожньо", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (перше (як-є ()))) (як-є ()) (як-є (а))) (як-є ()))"#, true),
        ("пари-праворуч-порожньо", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (перше (як-є ()))) (як-є (а)) (як-є ())) (як-є ()))"#, true),
        ("пари-усі-рівні", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є (а б в)) (як-є (а б в))) (як-є (так так так)))"#, true),
        ("пари-дві-рівні", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є (а б а)) (як-є (а б в))) (як-є (так так)))"#, true),
        ("пари-жодна", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є (а б)) (як-є (в г))) (як-є ()))"#, true),
        ("пари-коротша-ліва", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) так) (як-є (а)) (як-є (а б в))) (як-є (так)))"#, true),
        ("пари-коротша-права", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) так) (як-є (а б в)) (як-є (а))) (як-є (так)))"#, true),
        ("пари-усі-хибні", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) ні) (як-є (а б в)) (як-є (а б в))) (як-є ()))"#, true),
        ("пари-складені", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є ((а) (б) (а))) (як-є ((а) (в) (а)))) (як-є (так так)))"#, true),
        ("пари-одна-не-три", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) так) (як-є (а)) (як-є (а б в))) (як-є (так так так)))"#, false),
        ("пари-не-переплутати", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є (а б а)) (як-є (а б в))) (як-є (так)))"#, false),
        ("пари-не-хост-число", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) (однакові? лівий правий)) (як-є (а)) (як-є (а))) (як-є а))"#, false),
        ("пари-не-ні", r#"(однакові? (порахувати-пари-за-умовою-унарно (функція (лівий правий) ні) (як-є (а)) (як-є (а))) (як-є ні))"#, false),
        ("одно-не-пропустити-дві", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) так) (як-є (а б))) (як-є (так)))"#, false),
        ("одно-не-порахувати-атом-замість-списку", r#"(однакові? (порахувати-за-умовою-унарно (функція (елемент) (однакові? елемент (як-є (а)))) (як-є (а (а)))) (як-є (так так)))"#, false),
    ] {
        let value = eval_program(program, &mut session)
            .unwrap_or_else(|error| {
                panic!(
                    "test_id=D11-COUNT-UNARY-{id} layer=SENS input={program} expected=D1:{expected} actual_error={error}"
                )
            })
            .value;
        assert_eq!(
            value.as_predicate_bit(),
            Some(expected),
            "test_id=D11-COUNT-UNARY-{id} layer=SENS input={program} expected=D1:{expected} actual={value}"
        );
    }
}
