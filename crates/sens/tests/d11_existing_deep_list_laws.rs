//! Д11: вісім похідних бібліотечних законів з реального виконавця SENS.
//! Rust тільки запускає SENS, не повторює семантику списків.
use sens::{eval_program, load_core_library, Session};

fn witness(library: &str, cases: &[(&str, bool)]) {
    let mut session = Session::bare();
    load_core_library(&mut session).expect("test_id=D11-LIST-LAWS-CORE");
    eval_program(library, &mut session).expect("test_id=D11-LIST-LAWS-LIBRARY");
    for (program, expected) in cases {
        let actual = eval_program(program, &mut session)
            .unwrap_or_else(|e| panic!("test_id=D11-LIST-LAWS layer=SENS input={program} expected=D1:{expected} error={e}"))
            .value;
        assert_eq!(actual.as_predicate_bit(), Some(*expected),
            "test_id=D11-LIST-LAWS layer=SENS input={program} expected=D1:{expected} actual={actual}");
    }
}

#[test]
fn d11_adjacent_runs_native() {
    witness(include_str!("../../../lib/list-count-consecutive-atomic-runs-unary-general.lisp"), &[
        ("(однакові? (порахувати-сусідні-атомні-серії (як-є ())) (як-є ()))", true),
        ("(однакові? (порахувати-сусідні-атомні-серії (як-є (а а))) (як-є (атом?)))", true),
        ("(однакові? (порахувати-сусідні-атомні-серії (як-є (а б а))) (як-є (атом? атом? атом?)))", true),
        ("(однакові? (порахувати-сусідні-атомні-серії (як-є (а (б) а))) (як-є (атом? атом?)))", true),
        ("(однакові? (порахувати-сусідні-атомні-серії (як-є (а а б б))) (як-є (атом? атом? атом?)))", false),
    ]);
}

