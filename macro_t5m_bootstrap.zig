//! Фізичний bootstrap: Zig читає тільки готовий Т5М, відновлює точні
//! ширини/біти й видає дані для Rust. Семантику допускає сам SENS.
const std = @import("std");
const t5m = @import("research/zig-codecs/t5m.zig");
const physical = @embedFile("lib/macro.sens");

pub fn main(init: std.process.Init) !void {
    const allocator = init.arena.allocator();
    var decoded = try t5m.decode(allocator, physical);
    defer decoded.deinit(allocator);

    // Перед видачею перевіряємо канонічність того самого фізичного носія.
    const words = try allocator.alloc(t5m.Word, decoded.words.len);
    defer allocator.free(words);
    for (decoded.words, 0..) |word, index| {
        words[index] = .{ .width = word.width, .bits = word.bits };
    }
    const replay = try t5m.encode(allocator, words);
    defer allocator.free(replay);
    if (!std.mem.eql(u8, physical, replay)) return error.NonCanonicalBootstrap;

    var buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    const output = &stdout.interface;
    try output.writeAll("// Generated by pinned Zig from lib/macro.sens.\n");
    try output.writeAll("static MACRO_BOOTSTRAP_WORDS: &[(usize, &[u8])] = &[\n");
    for (decoded.words) |word| {
        try output.print("    ({d}, &[", .{word.width});
        for (word.bits, 0..) |bit, index| {
            if (index != 0) try output.writeAll(", ");
            try output.print("{d}", .{bit - '0'});
        }
        try output.writeAll("]),\n");
    }
    try output.writeAll("];\n");
    try output.flush();
}
