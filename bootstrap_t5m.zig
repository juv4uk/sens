//! Типовий bootstrap: Zig відновлює точні ширини/біти готового Т5М.
//! Окремий --projection-tables передає незмінені джерела людських проєкцій
//! build-каталогу; це не машинні значення. Семантику допускає сам SENS.
const std = @import("std");
const t5m = @import("research/zig-codecs/t5m.zig");
const projections = @import("domain_projection_assets.zig");

pub fn main(init: std.process.Init) !void {
    const allocator = init.arena.allocator();
    var buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buffer);
    const output = &stdout.interface;
    const args = try init.minimal.args.toSlice(allocator);
    if (args.len == 2 and std.mem.eql(u8, args[1], "--projection-tables")) {
        try projections.writeBuildTables(output);
        try output.flush();
        return;
    }
    if (args.len != 1) return error.UnknownBootstrapMode;
    const libraries = [_]struct { name: []const u8, physical: []const u8 }{
        .{ .name = "MACRO_BOOTSTRAP_WORDS", .physical = @embedFile("lib/macro.sens") },
        .{ .name = "CORE3_BOOTSTRAP_WORDS", .physical = @embedFile("lib/core3.sens") },
        .{ .name = "CORE4_BOOTSTRAP_WORDS", .physical = @embedFile("lib/core4.sens") },
        .{ .name = "COMPILER_NUCLEUS_BOOTSTRAP_WORDS", .physical = @embedFile("lib/compiler-nucleus.sens") },
        .{ .name = "TIME_BOOTSTRAP_WORDS", .physical = @embedFile("lib/time.sens") },
        .{ .name = "UTF8_BOOTSTRAP_WORDS", .physical = @embedFile("lib/utf8.sens") },
        .{ .name = "PROCESS_BOOTSTRAP_WORDS", .physical = @embedFile("lib/process.sens") },
        .{ .name = "TCP_BOOTSTRAP_WORDS", .physical = @embedFile("lib/tcp.sens") },
        .{ .name = "FS_BOOTSTRAP_WORDS", .physical = @embedFile("lib/fs.sens") },
    };
    for (libraries) |library| {
        try emitWords(allocator, output, library.name, library.physical);
    }
    try emitSha256(output, "LANGUAGE_CONTRACT_SHA256", @embedFile("language-contract.lisp"));
    try emitSha256(
        output,
        "BIJA3_L1_L5_RATIFICATION_SHA256",
        @embedFile("contracts/bija3-l1-l5-ratification.lisp"),
    );
    try emitSha256(
        output,
        "D4_BOOTSTRAP_RATIFICATION_SHA256",
        @embedFile("contracts/d4-bootstrap-ratification.lisp"),
    );
    try output.flush();
}

fn emitSha256(output: *std.Io.Writer, name: []const u8, bytes: []const u8) !void {
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    var hex: [64]u8 = undefined;
    _ = std.fmt.bufPrint(&hex, "{x}", .{digest}) catch unreachable;
    try output.writeAll("pub(super) const ");
    try output.writeAll(name);
    try output.writeAll(": &str = \"");
    try output.writeAll(&hex);
    try output.writeAll("\";\n");
}

fn emitWords(allocator: std.mem.Allocator, output: *std.Io.Writer, name: []const u8, physical: []const u8) !void {
    var decoded = try t5m.decode(allocator, physical);
    defer decoded.deinit(allocator);

    // Перед видачею перевіряємо канонічність того самого фізичного носія.
    const words = try allocator.alloc(t5m.Word, decoded.words.len);
    defer allocator.free(words);
    for (decoded.words, 0..) |word, index| {
        words[index] = .{ .width = word.width, .bits = word.bits };
    }
    const replay = try t5m.encode(allocator, words);
    defer allocator.free(replay);
    if (!std.mem.eql(u8, physical, replay)) return error.NonCanonicalBootstrap;

    try output.writeAll("// Generated by pinned Zig from canonical T5M.\n");
    try output.print("static {s}: &[(usize, &[u8])] = &[\n", .{name});
    for (decoded.words) |word| {
        try output.print("    ({d}, &[", .{word.width});
        for (word.bits, 0..) |bit, index| {
            if (index != 0) try output.writeAll(", ");
            try output.print("{d}", .{bit - '0'});
        }
        try output.writeAll("]),\n");
    }
    try output.writeAll("];\n");
}
