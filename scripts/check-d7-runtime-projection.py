#!/usr/bin/env python3
"""Generate Rust's D7 display-only table exclusively from the current 128/128 owner map.

Phonemic D7 v1 and its 126/128 reservations are not code inputs.
No generated glyph supplies a callable SENS source head.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

from domain_tables import D7_TABLE, read_domain_table

ROOT = Path(__file__).resolve().parents[1]
AUTHORITY = ROOT / "knowledge/d7-keyboard-v2-ratified.json"
GENERATED = ROOT / "crates/sens/src/d7_display_registry_generated.rs"


def rust_glyph(value: str) -> str:
    code = ord(value)
    if code < 32 or code == 127:
        return '"\\u{' + f"{code:x}" + '}"'
    return json.dumps(value, ensure_ascii=False)


def render() -> str:
    doc = json.loads(AUTHORITY.read_text(encoding="utf-8"))
    if (doc.get("schema"), doc.get("status"), doc.get("width"),
            doc.get("capacity"), doc.get("occupancy")) != (
            "sens.d7.keyboard/v2", "owner-ratified", 7, 128, 128):
        raise ValueError("D7 current ratified authority mismatch")
    rows = read_domain_table(D7_TABLE)
    table = doc.get("table")
    if len(rows) != 128 or not isinstance(table, list) or len(table) != 128:
        raise ValueError("D7 v2 requires exactly 128 rows")
    for surface in ("ascii", "uk", "san"):
        values = [row[surface] for row in table]
        if len(set(values)) != 128 or any(len(value) != 1 for value in values):
            raise ValueError(f"D7 {surface} is not bijective")
    parts = [
        "// GENERATED — DO NOT EDIT BY HAND.",
        "// D7 owner: knowledge/d7-keyboard-v2-ratified.json (128/128).",
        "// Generated by scripts/check-d7-runtime-projection.py.",
        "// W7 text projection only; never authorizes a callable.",
        "",
        "#[derive(Clone, Copy)]",
        "pub(super) struct D7DisplayRow {",
        "    pub(super) bits: u8,",
        "    pub(super) uk: Option<&'static str>,",
        "    pub(super) sa: Option<&'static str>,",
        "    pub(super) deva: Option<&'static str>,",
        "    pub(super) slp1: Option<&'static str>,",
        "    pub(super) en: Option<&'static str>,",
        "    pub(super) en_ipa: Option<&'static str>,",
        "}",
        "",
        "pub(super) const D7_DISPLAY_ROWS: &[D7DisplayRow] = &[",
    ]
    for index, (entry, row) in enumerate(zip(table, rows)):
        bits = f"{index:07b}"
        if entry["bits"] != bits or row.bits != bits or row.lisp is not None:
            raise ValueError(f"D7:{bits} coordinate/callability drift")
        visible = (entry["uk"], entry["san"], entry["ascii"])
        expected = (None, None, None) if index < 32 or index == 127 else visible
        if (row.uk, row.san, row.en) != expected:
            raise ValueError(f"D7:{bits} domain table drift")
        uk, san, en = (rust_glyph(entry[key]) for key in ("uk", "san", "ascii"))
        parts.append(
            f"    D7DisplayRow {{ bits: 0b{bits}, uk: Some({uk}), sa: Some({san}), "
            f"deva: Some({san}), slp1: None, en: Some({en}), en_ipa: None }},"
        )
    parts += ["];", ""]
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        GENERATED.write_text(expected, encoding="utf-8")
    elif GENERATED.read_text(encoding="utf-8") != expected:
        raise SystemExit("D7-DISPLAY-PROJECTION: BLOCKED — Rust table differs from 128/128 v2")
    print("D7-DISPLAY-PROJECTION: PASS — 128 W7 cells from current ratified table")


if __name__ == "__main__":
    main()
