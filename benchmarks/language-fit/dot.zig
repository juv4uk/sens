// Нативний математичний кернел Zig 0.16.0 для порівняння з C, Fortran, Rust і ASM.
// Ті самі подвійні числа, довжина та порядок скалярного підсумовування.
// Це справжній код Zig, експортований за C ABI для спільного драйвера dot.c.
// Zig тут не виконує мовної семантики СЕНС.
export fn sens_dot_zig(a: [*]const f64, b: [*]const f64, n: usize) f64 {
    var sum: f64 = 0.0;
    for (0..n) |i| {
        sum += a[i] * b[i];
    }
    return sum;
}
