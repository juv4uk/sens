#!/usr/bin/env python3
"""#2701 theorem-first D5 -> D6 one-delta search.

This witness asks a semantic question, not a coordinate question:

    Does the current ratified/generated D5 population contain any resident
    whose newly observed same-base + exactly-one-delta child is not already
    explained by an admitted generator law?

Current expected result:
    NO-NEW-D5-ONE-DELTA-CHILD

The selector family is a positive control.  Every admitted D5 selector has
exactly two admitted D6 selector children, already generated by the same
selector extension laws.  UNKNOWN/free D5 coordinates are not residents and
cannot serve as parents.
"""

from __future__ import annotations

import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D5_MAP = ROOT / "benchmarks" / "d5-closure-map" / "run.py"
D6_MAP = ROOT / "benchmarks" / "d6-closure-map" / "run.py"
D5_ELIGIBILITY = ROOT / "benchmarks" / "d5-sens-derivation-closeout" / "factor-eligibility.json"


def load_rows(script: Path) -> list[dict]:
    ns = runpy.run_path(str(script))
    return ns["build_map"]()


def main() -> int:
    d5_rows = load_rows(D5_MAP)
    d6_rows = load_rows(D6_MAP)
    eligibility = json.loads(D5_ELIGIBILITY.read_text(encoding="utf-8"))

    d5_members = [r for r in d5_rows if r["semantic_member_of_ratified_domain"]]
    d6_members = [r for r in d6_rows if r["semantic_member_of_ratified_domain"]]

    assert len(d5_members) == 8, f"expected 8 current D5 semantic members, got {len(d5_members)}"
    assert len(d6_members) == 16, f"expected 16 current D6 semantic members, got {len(d6_members)}"

    assert all(r["status"] == "generated" for r in d5_members)
    assert all(r["semantic_family"] == "selector" for r in d5_members)
    assert not any(
        r["semantic_member_of_ratified_domain"] and r["semantic_family"] != "selector"
        for r in d5_rows
    ), "current D5 contains a non-selector semantic member; theorem search must reopen"

    expected_children = {
        parent["coordinate"] + bit
        for parent in d5_members
        for bit in ("0", "1")
    }
    actual_d6 = {r["coordinate"] for r in d6_members}

    assert expected_children == actual_d6, (
        "current D5 selector members do not generate exactly the current D6 selector closure: "
        f"missing={sorted(expected_children-actual_d6)} "
        f"extra={sorted(actual_d6-expected_children)}"
    )

    for child in d6_members:
        parent = child["coordinate"][:-1]
        parent_row = next(r for r in d5_members if r["coordinate"] == parent)
        assert parent_row["semantic_family"] == child["semantic_family"] == "selector"
        assert child["semantic_law"] == parent_row["semantic_law"]
        assert child["semantic_law_authority"] == parent_row["semantic_law_authority"]

    yes_rows = [
        row for row in eligibility["factors"]
        if row.get("d5_eligible") == "YES"
    ]
    assert not yes_rows, f"new D5-eligible factors exist and require D6 child analysis: {yes_rows}"

    unknown_free = [r for r in d5_rows if r["status"] == "UNKNOWN/free"]
    assert len(unknown_free) == 24
    assert not any(r["semantic_member_of_ratified_domain"] for r in unknown_free)

    print("D6-THEOREM-FIRST-D5-CHILD=PASS")
    print(f"d5-semantic-members={len(d5_members)}")
    print(f"d5-selector-members={len(d5_members)}")
    print("d5-nonselector-members=0")
    print(f"known-d6-one-delta-children={len(actual_d6)}")
    print("unexplained-d6-one-delta-children=0")
    print(f"d5-unknown-nonparents={len(unknown_free)}")
    print("new-d5-eligible-factors=0")
    print("RESULT=NO-NEW-D5-ONE-DELTA-CHILD")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
