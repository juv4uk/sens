// Сфера Rust: механізм.
// ЦІЛЬ: D6 додати-1 (001110), lib/domains/d6.lisp:23.
// Міряє лише розбір десяткового запису в точне ціле — не семантику.
use std::time::Instant;

fn main() {
    let запис = "1";
    let mut найкраще = u128::MAX;
    for _ in 0..100_000 {
        let початок = Instant::now();
        let значення: u64 = запис.parse().expect("точний десятковий запис");
        let тривало = початок.elapsed().as_nanos();
        assert_eq!(значення, 1);
        if тривало < найкраще {
            найкраще = тривало;
        }
    }
    println!("раст-механізм: найкращий розбір {найкраще} нс");
}
