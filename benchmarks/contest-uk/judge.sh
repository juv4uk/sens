#!/usr/bin/env bash
# Нативний конкурс: SENS виконує, Zig звіряє T5M; Python/JSON не беруть участі.
set -euo pipefail
cd "$(dirname "$0")/../.."
sens="${SENS_BIN:-$PWD/target/debug/sens}"
trit="${SENS_TRIT_BIN:-$PWD/target/debug/sens-trit}"
[[ -x "$sens" && -x "$trit" ]] || { echo "Зберіть sens + sens-trit з --features benchmark-ast-visits" >&2; exit 2; }
error() { printf "КОНКУРС: ПОМИЛКА %s\n" "$*" >&2; exit 2; }
# При RED прибрати тільки поточні тимчасові файли, не змінюючи Lisp/T5M.
tmp=""
trap 'if [[ -n "$tmp" ]]; then rm -rf -- "$tmp"; fi' EXIT
# Непарні кандидати ще не є програмами конкурсу: повідомляємо їх
# окремо, але не зупиняємо нативний суд уже наявних фізичних трійок.
# Це не зарахування source-only Lisp: без Zig/T5M і реального SENS
# такий файл не входить до inputs, метрик або списку переможців.
pending_native_pair=0
if (( $# == 0 )); then
  for source in benchmarks/contest-uk/*.lisp; do
    [[ -e "$source" || -L "$source" ]] || continue
    [[ -f "$source" && ! -L "$source" ]] || error "некоректне Lisp-джерело $source"
    physical="${source%.lisp}.sens"
    view="${source%.lisp}"
    if [[ ! -s "$physical" || ! -f "$view" ||
          -L "$physical" || -L "$view" ]]; then
      # Лише цілком відсутня пара означає чергу на рідний remint.
      # Напівпара, порожні байти або symlink — справжній RED, не pending:
      # інакше чинний суд приховує незворотний фізичний носій.
      if [[ -e "$physical" || -L "$physical" ||
            -e "$view" || -L "$view" ]]; then
        error "неповна або підмінена фізична пара source=$source physical=$physical view=$view"
      fi
      echo "CONTEST_PENDING_NATIVE_PAIR source=$source status=NOT_EXECUTED" >&2
      pending_native_pair=$((pending_native_pair + 1))
    fi
  done
fi
# Автоматично включати нові реальні трійки до конкурсу:
# оптимізована програма не має залежати від ручної реєстрації.
if (( $# )); then
  # Явний одиничний виклик вимірює саме названого учасника.
  inputs=("$@")
else
  # Без аргументів усі нові трійки вступають автоматично.
  inputs=(benchmarks/contest-uk/*.sens)
  [[ -f "${inputs[0]}" ]] || error "немає жодного чинного фізичного T5M учасника"
fi
declare -A seen
rows=""
for path in "${inputs[@]}"; do
  # Ручний запуск приймає тільки чинних учасників безпосередньо в contest-uk/.
  # Bash-шаблон *.sens у [[ ]] збігається також із вкладеним superseded/*.sens:
  # він помилково повертав архівні програми до активного суду.
  [[ "$path" == benchmarks/contest-uk/*.sens &&
     "${path#benchmarks/contest-uk/}" != */* ]] || error "некоректний шлях: $path"
  [[ -z "${seen[$path]+yes}" ]] || continue
  seen[$path]=1
  source="${path%.sens}.lisp"; view="${path%.sens}"
  [[ -s "$path" && -f "$source" && -f "$view" &&
     ! -L "$path" && ! -L "$source" && ! -L "$view" ]] || error "неповна трійка $path"
  name="${path##*/}"; name="${name%.sens}"
  case "$name" in
    поліном-кубічний|поліном-кубічний-*) task="поліном-кубічний"; expected="194";;
    акерман|акерман-*) task="акерман"; expected="61";;
    факторіал|факторіал-*) task="факторіал"; expected="3628800";;
    подвійний-факторіал|подвійний-факторіал-*) task="подвійний-факторіал"; expected="945";;
    сума-до-n|сума-до-n-*) task="сума-до-n"; expected="5050";;
    довжина-списку|довжина-списку-*) task="довжина-списку"; expected="8";;
    фібоначчі|фібоначчі-*) task="фібоначчі"; expected="55";;
    степінь-двійки|степінь-двійки-*) task="степінь-двійки"; expected="1024";;
    сума-квадратів|сума-квадратів-*) task="сума-квадратів"; expected="385";;
    сума-кубів|сума-кубів-*) task="сума-кубів"; expected="3025";;
    сума-четвертих-степенів|сума-четвертих-степенів-*) task="сума-четвертих-степенів"; expected="25333";;
    сума-парних|сума-парних-*) task="сума-парних"; expected="10100";;
    сума-непарних-квадратів|сума-непарних-квадратів-*) task="сума-непарних-квадратів"; expected="1330";;
    сума-непарних|сума-непарних-*) task="сума-непарних"; expected="289";;
    сума-трикутних|сума-трикутних-*) task="сума-трикутних"; expected="220";;
    трикутне|трикутне-*) task="трикутне"; expected="55";;
    нсд|нсд-*) task="нсд"; expected="21";;
    четвертий-степінь|четвертий-степінь-*) task="четвертий-степінь"; expected="2401";;
    квадрат|квадрат-*) task="квадрат"; expected="144";;
    куб|куб-*) task="куб"; expected="343";;
    різниця-квадратів|різниця-квадратів-*) task="різниця-квадратів"; expected="91";;
    модуль|модуль-*) task="модуль"; expected="17";;
    максимум|максимум-*) task="максимум"; expected="17";;
    мінімум|мінімум-*) task="мінімум"; expected="-17";;
    відстань|відстань-*) task="відстань"; expected="29";;
    різниця-кубів|різниця-кубів-*) task="різниця-кубів"; expected="279";;
    кількість-пар|кількість-пар-*) task="кількість-пар"; expected="45";;
    кількість-атомів|кількість-атомів-*) task="кількість-атомів"; expected="2";;
    кількість-трійок|кількість-трійок-*) task="кількість-трійок"; expected="120";;
    центроване-квадратне|центроване-квадратне-*) task="центроване-квадратне"; expected="85";;
    центроване-трикутне|центроване-трикутне-*) task="центроване-трикутне"; expected="136";;
    центроване-шестикутне|центроване-шестикутне-*) task="центроване-шестикутне"; expected="271";;
    пентагональне|пентагональне-*) task="пентагональне"; expected="145";;
    семикутне|семикутне-*) task="семикутне"; expected="235";;
    восьмикутне|восьмикутне-*) task="восьмикутне"; expected="280";;
    шестикутне|шестикутне-*) task="шестикутне"; expected="190";;
    добуток-сусідів|добуток-сусідів-*) task="добуток-сусідів"; expected="156";;
    перевернути|перевернути-*) task="перевернути"; expected="(5 4 3 2 1)";;
    лише-атоми|лише-атоми-*) task="лише-атоми"; expected="(1 3)";;
    розгорнути-один|розгорнути-один-*) task="розгорнути-один"; expected="(4 3 2 1)";;
    збільшити-всі|збільшити-всі-*) task="збільшити-всі"; expected="(4 3 2)";;
    *) error "невідома задача $name";;
  esac
  tmp="$(mktemp -d)"
  "$sens" --t5m-mint "$source" "$tmp/minted.sens" >/dev/null || error "mint $path"
  if ! cmp -s "$path" "$tmp/minted.sens"; then
    # Ідентичність — exact byte equality; не створюємо hash-квитанцій.
    error "REGRESSION id=contest-native-mint-parity layer=physical-pair source=$source physical=$path expected=byte-identical actual=byte-different"
  fi
  "$trit" open "$path" > "$tmp/view" || error "Zig open $path"
  cmp -s "$view" "$tmp/view" || error "необоротний вигляд $path"
  "$trit" verify-view "$path" >/dev/null || error "Zig verify-view $path"
  "$sens" --t5m-pair "$source" "$path" --core4-runtime > "$tmp/paired" || error "SENS paired $path"
  "$trit" eval-core4 "$path" > "$tmp/standalone" || error "SENS standalone $path"
  cmp -s "$tmp/paired" "$tmp/standalone" || error "розбіжність виконання $path"
  { cat "$source"; printf "\n(як-є ())\n"; } > "$tmp/mutant.lisp"
  if "$sens" --t5m-pair "$tmp/mutant.lisp" "$path" --core4-runtime >/dev/null 2>"$tmp/negative"; then error "мутант прийнято $path"; fi
  grep -Fq T5M_PHYSICAL_PAIR_MISMATCH "$tmp/negative" || error "некоректна негативна перевірка $path"
  # Звичайний конкурс має AST/visits. Інтеграційний суд без фічі
  # benchmark-ast-visits перевіряє ті самі живі входи й самостійний
  # SENS, але НЕ видає невиміряні показники за числові.
  if [[ "${SENS_CONTEST_PROOF_ONLY:-false}" == true ]]; then
    result="$(tail -n 1 "$tmp/standalone")"
    nodes="НЕ_ВИМІРЮВАЛОСЯ"; visits="НЕ_ВИМІРЮВАЛОСЯ"
  else
    if ! "$sens" --benchmark-physical "$path" --core4-runtime > "$tmp/bench.out" 2>"$tmp/bench.err"; then
      sed 's/^/SENS physical benchmark: /' "$tmp/bench.err" >&2
      if [[ -s "$tmp/bench.out" ]]; then
        sed 's/^/SENS physical benchmark stdout: /' "$tmp/bench.out" >&2
      fi
      error "нативні метрики $path"
    fi
    cmp -s "$tmp/standalone" "$tmp/bench.out" || error "бенчмарк змінив результат $path"
    line="$(grep "^SENS_BINARY_BENCH " "$tmp/bench.err")" || error "немає метрик $path"
    [[ "$line" =~ ^SENS_BINARY_BENCH[[:space:]]AST_NODES=([0-9]+)[[:space:]]EVAL_VISITS=([0-9]+)[[:space:]]RESULT=(.+)$ ]] || error "невірні метрики $path"
    nodes="${BASH_REMATCH[1]}"; visits="${BASH_REMATCH[2]}"; result="${BASH_REMATCH[3]}"
  fi
  [[ "$(tail -n 1 "$tmp/standalone")" == "$result" ]] || error "результат метрик відмінний $path"
  # Перевірені задачі мають незалежний числовий еталон. Перший
  # конкурсант НЕ може визначати правильність усіх наступних.
  [[ "$result" == "$expected" ]] || error "хибне значення $path: отримано=$result очікувано=$expected"
  # Повне байтове порівняння: command substitution відкидає кінцеві LF
  # і могло зарахувати зайві порожні рядки як коректний результат.
  printf '%s\n' "$expected" > "$tmp/expected"
  cmp -s "$tmp/standalone" "$tmp/expected" || error "хибний вивід $path: очікувано=$expected (зайві/відсутні байти)"
  # Справжні змінні входи: константа замість алгоритму не виграє.
  # Додаємо виклик до тієї самої програми у scratch (оригінал не чіпаємо).
  # Всі свідки проходять реальний SENS -> Zig/T5M -> SENS, без Python/JSON.
  final_call="$(grep -vE '^[[:space:]]*(;|$)' "$source" | tail -n 1)"
  if [[ "$final_call" =~ ^\(([^[:space:]()]+)[[:space:]] ]]; then
    function_name="${BASH_REMATCH[1]}"
  else
    error "не можна прочитати фінальний виклик конкурсанта $source"
  fi
  case "$task" in
    поліном-кубічний)
      # Поліном х^3+2х^2+3х+4: нуль, відємні та додатні входи.
      # Незалежні результати перевіряє реальний SENS через Zig T5M.
      witnesses=("0|4" "1|10" "2|26" "-2|-2" "5|194" "10|1234");;
    акерман)
      # A(3,н)=2^(н+3)-3. Кожен вхід обчислює сам SENS, не скрипт.
      witnesses=("0|5" "1|13" "2|29" "3|61" "4|125");;
    факторіал)
      # Порівнюємо однаковий факторіал для двох допустимих SENS API:
      # хвостовий (н а) та звичайний рекурсивний (н).
      # Рішення про істину приймає тільки нативне виконання SENS.
      if [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]][^[:space:]()]+[)]$ ]]; then
        witnesses=("0|1" "5|120" "7|5040")
      else
        # Нульовий випадок та ненульовий накопичувач не дозволяють
        # підмінити хвостовий інтерфейс одноаргументною рекурсією.
        witnesses=("0 1|1" "5 1|120" "7 1|5040"
                   "0 3|3" "5 2|240")
      fi;;
    подвійний-факторіал)
      # Для парного й непарного n, включно з двома базовими випадками.
      # Справжня рекурсія через SENS: не константа 945.
      witnesses=("0|1" "1|1" "2|2" "6|48" "9|945" "10|3840");;
    сума-до-n)
      # Та сама задача суми 1..н: один аргумент н або н з нульовим
      # початковим накопичувачем. Обидва алгоритми перевіряє SENS
      # на кількох вхідних значеннях (не лише на 100).
      if [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]][^[:space:]()]+[)]$ ]]; then
        witnesses=("0|0" "10|55" "20|210")
      else
        witnesses=("0 0|0" "10 0|55" "20 0|210")
      fi;;
    фібоначчі)
      # Унарне fib(н) та хвостове fib(н, а, б) конкурують за один
      # результат, але проходять власні живі змінні входи в SENS.
      if [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]]+[^[:space:]()]+[)]$ ]]; then
        witnesses=("0|0" "5|5" "7|13")
      else
        witnesses=("0 0 1|0" "5 0 1|5" "7 0 1|13")
      fi;;
    сума-квадратів)
      # Справжня сума квадратів від 1 до н, а не підставлена 385.
      # Кожний вхід проходить SENS mint → Zig/T5M → парне/самостійне виконання.
      witnesses=("0|0" "1|1" "3|14" "7|140" "12|650");;
    нсд)
      # Евклід на незалежних парах: константа 21 не пройде.
      witnesses=("0 5|5" "54 24|6" "17 13|1" "48 18|6" "252 105|21");;
    сума-кубів)
      # Окремі числові еталони: константний вивід 3025 не пройде.
      witnesses=("0|0" "1|1" "3|36" "5|225" "8|1296");;
    сума-четвертих-степенів)
      # S(н)=Σк^4: змінні значення, нуль, межі та н>10.
      # Формула й рекурсія мусять погодитись із незалежною арифметикою.
      # 30 перевіряє реальний D24→D48 проміжок: ділити великий D48
      # чисельник на D24 літерал після множення семантично не дозволено.
      witnesses=("0|0" "1|1" "2|17" "3|98" "5|979" "7|4676" "12|60710" "20|722666" "30|5273999");;
    сума-парних)
      # Обидва інтерфейси обчислюють один закон: n(n+1).
      # Рекурсивний варіант має явний нульовий акумулятор,
      # формула має один аргумент. Перевіряє саме SENS+Zig.
      if [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]][^[:space:]()]+[[:space:]][^[:space:]()]+[)]$ ]]; then
        witnesses=("0 0|0" "1 0|2" "2 0|6" "5 0|30" "10 0|110" "100 0|10100")
      elif [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]][^[:space:]()]+[)]$ ]]; then
        witnesses=("0|0" "1|2" "2|6" "5|30" "10|110" "100|10100")
      else
        error "невідома сигнатура суми парних: $final_call"
      fi;;
    сума-непарних)
      # Відрізнити O(1) формулу н² від константи та хибної суми парних.
      witnesses=("0|0" "1|1" "2|4" "5|25" "12|144" "17|289");;
    сума-трикутних)
      # Сума T(1)..T(н), контроль нуля, меж і непарних н: не константа 220.
      witnesses=("0|0" "1|1" "2|4" "3|10" "5|35" "10|220" "12|364");;
    трикутне)
      # T(н)=н(н+1)/2: незалежний нуль, обидві межі, різні входи.
      # Формула та рекурсія обчислюються справжнім SENS/Zig T5M.
      witnesses=("0|0" "1|1" "2|3" "3|6" "5|15" "10|55" "20|210" "25|325");;
    степінь-двійки)
      # Одноаргументний степінь також допустимий; додатковий
      # акумулятор перевіряємо окремо, не змінюючи базової істини.
      if [[ "$final_call" =~ ^[(][^[:space:]()]+[[:space:]]+[^[:space:]()]+[)]$ ]]; then
        witnesses=("0|1" "1|2" "5|32" "8|256")
      else
        witnesses=("0 1|1" "1 1|2" "5 1|32" "8 3|768")
      fi;;
    четвертий-степінь)
      # Змінні входи перевіряє лише справжній SENS через Zig/T5M.
      witnesses=("0|0" "1|1" "2|16" "3|81" "5|625" "7|2401" "12|20736" "-3|81" "-7|2401" "30|810000");;
    квадрат) witnesses=("0|0" "5|25" "-7|49" "13|169");;
    куб) witnesses=("0|0" "2|8" "5|125" "-3|-27");;
    різниця-квадратів)
      # Дві математично рівні формули, різні AST і фізичний T5M.
      witnesses=("0 0|0" "5 2|21" "7 7|0" "-3 1|8" "12 5|119" "-7 -2|45");;
    модуль)
      witnesses=("0|0" "7|7" "-7|7" "-1|1" "17|17");;
    максимум)
      # Рівність, обидва порядки, відʼємні аргументи і нуль.
      # Лише справжнє SENS виконання, не зафіксована константа 17.
      witnesses=("0 0|0" "7 4|7" "2 9|9" "-3 -1|-1" "-7 -12|-7" "17 12|17");;
    відстань)
      # Тотожність |а-б| на рівних, переставлених і відʼємних цілих.
      # Ніякої константи 29 замість рідного алгоритму SENS.
      witnesses=("0 0|0" "7 4|3" "2 9|7" "-3 -1|2" "-7 -12|5" "-17 12|29" "12 -17|29");;
    мінімум)
      # Мінімум має бути правильним і при рівності та двох відʼємних.
      witnesses=("0 0|0" "7 4|4" "2 9|2" "-3 -1|-3" "-7 -12|-12" "-17 12|-17");;
    різниця-кубів)
      witnesses=("0 0|0" "7 4|279" "3 3|0" "-3 1|-28" "5 -2|133" "0 2|-8");;
    кількість-пар)
      # C(н,2): незалежні межі та несиметричні додатні входи.
      # Закон 0,1 -> 0; 2 -> 1; 5 -> 10; 10 -> 45; 20 -> 190.
      witnesses=("0|0" "1|0" "2|1" "5|10" "10|45" "20|190");;
    кількість-трійок)
      # C(н,3): незалежні крайові та великі входи, не константа 120.
      witnesses=("0|0" "1|0" "2|0" "3|1" "5|10" "10|120" "20|1140");;
    сума-непарних-квадратів)
      # Сума (2к-1)^2: нуль, перші значення та масштабування D24+.
      witnesses=("0|0" "1|1" "2|10" "3|35" "5|165" "10|1330" "20|10660");;
    центроване-квадратне)
      # Два незалежні алгоритми, сім живих D24+ вхідних значень.
      witnesses=("1|1" "2|5" "3|13" "4|25" "7|85" "10|181" "20|761");;
    центроване-трикутне)
      # Розкладена й нерозкладена формули з незалежними точними свідками.
      witnesses=("0|1" "1|1" "2|4" "3|10" "5|31" "7|64" "10|136" "20|571");;
    центроване-шестикутне)
      # Формула і різниця кубів на однакових D24+ входах.
      witnesses=("0|1" "1|1" "2|7" "3|19" "4|37" "7|127" "10|271" "20|1141");;
    пентагональне)
      witnesses=("0|0" "1|1" "2|5" "3|12" "5|35" "7|70" "10|145" "12|210");;
    восьмикутне)
      # Восьмикутні числа н(3н-2): справжні SENS/Zig/T5M змінні входи.
      witnesses=("0|0" "1|1" "2|8" "3|21" "4|40" "5|65" "10|280" "20|1160");;
    семикутне)
      # Два різні точні закони — формула і складення із трикутних.
      witnesses=("0|0" "1|1" "2|7" "3|18" "4|34" "5|55" "7|112" "10|235" "20|970");;
    добуток-сусідів)
      # Тотожність n(n+1)=n²+n, включно з нулем, відʼємними й великими.
      witnesses=("0|0" "1|2" "2|6" "5|30" "-1|0" "-3|6" "-12|132" "12|156" "20|420");;
    шестикутне)
      witnesses=("0|0" "1|1" "2|6" "3|15" "4|28" "5|45" "10|190" "20|780");;
    перевернути)
      # Ратифікований Д5:10100 ЗВОРОТ має один аргумент,
      # бібліотечні рекурсивні учасники — список та акумулятор.
      # Обидва профілі виконуються тільки в SENS через Zig/T5M.
      # Передавати Д5 зайвий акумулятор означає відхилити
      # коротшого конкурсанта ще до фактичного змагання.
      if [[ "$function_name" == зворот ]]; then
        witnesses=("(як-є ())|()"
                   "(список 1)|(1)"
                   "(список 1 2 3)|(3 2 1)"
                   "(список 4 4 7 9)|(9 7 4 4)"
                   "(список 0 -3 2)|(2 -3 0)"
                   "(список 1 2)|(2 1)")
      else
        witnesses=("(як-є ()) (як-є ())|()"
                   "(список 1) (як-є ())|(1)"
                   "(список 1 2 3) (як-є ())|(3 2 1)"
                   "(список 4 4 7 9) (як-є ())|(9 7 4 4)"
                   "(список 0 -3 2) (як-є ())|(2 -3 0)"
                   "(список 1 2) (список 9 8)|(2 1 9 8)")
      fi;;
    кількість-атомів)
      # Однакова семантика, але різна арність: пряма рекурсія або акумулятор.
      # Визначення параметрів є джерелом арності, не випадкова цифра
      # у останньому виклику. Нативні варіативні входи перевіряє SENS/Zig.
      if grep -Eq '^[[:space:]]*\(функція[[:space:]]+\(с[[:space:]]+л\)' "$source"; then
        witnesses=("(як-є ()) 0|0"
                   "(список 1) 0|1"
                   "(список (список 2)) 0|0"
                   "(список 1 (список 2 3) 4) 0|2"
                   "(список 1 (як-є ()) 3) 0|3"
                   "(список 0 (список 2) -3) 2|4")
      elif grep -Eq '^[[:space:]]*\(функція[[:space:]]+\(с\)' "$source"; then
        witnesses=("(як-є ())|0"
                   "(список 1)|1"
                   "(список (список 2))|0"
                   "(список 1 (список 2 3) 4)|2"
                   "(список 1 (як-є ()) 3)|3"
                   "(список 0 (список 2) -3)|2")
      else
        error "Невідома арність підрахунку атомів у $source"
      fi;;
    лише-атоми)
      # Перевіряти справжню арність із самого Lisp: компактний фільтр
      # має один аргумент, історичні варіанти — початковий акумулятор.
      # Порожню вкладену пару не слід повертати як атом списку.
      if grep -Eq '^[[:space:]]*\(функція[[:space:]]+\([^[:space:]()]+\)' "$source"; then
        witnesses=("(як-є ())|()"
                   "(список 1)|(1)"
                   "(список 1 (список 2) 3)|(1 3)"
                   "(список (список 1 2) 3 4)|(3 4)"
                   "(список 0 (список) -3)|(0 -3)"
                   "(список 7 (список 8 9))|(7)"
                   "(список (як-є ()) 3)|(3)")
      else
        witnesses=("(як-є ()) (як-є ())|()"
                   "(список 1) (як-є ())|(1)"
                   "(список 1 (список 2) 3) (як-є ())|(1 3)"
                   "(список (список 1 2) 3 4) (як-є ())|(3 4)"
                   "(список 0 (список) -3) (як-є ())|(0 -3)"
                   "(список 7 (список 8 9)) (як-є ())|(7)"
                   "(список (як-є ()) 3) (як-є ())|(3)")
      fi;;
    розгорнути-один)
      # Визначена реалізацією рекурсія: усі рівні розкладаються,
      # атоми повертаються у зворотному порядку перед акумулятором.
      # Справжні змінні входи перевіряються SENS/Zig, не shell-оракулом.
      witnesses=("(як-є ()) (як-є ())|()"
                 "(список 1) (як-є ())|(1)"
                 "(список 1 (список 2 3) 4) (як-є ())|(4 3 2 1)"
                 "(список (список 1 (список 2 3)) 4) (як-є ())|(4 3 2 1)"
                 "(список (список) 0 -3) (як-є ())|(-3 0)"
                 "(список 1 (список 2 3) 4) (список 9 8)|(4 3 2 1 9 8)");;
    збільшити-всі)
      # Нативні змінні SENS/Zig входи, включно з початковим акумулятором.
      witnesses=("(як-є ()) (як-є ())|()"
                 "(список 1) (як-є ())|(2)"
                 "(список 1 2 3) (як-є ())|(4 3 2)"
                 "(список 0 -3 7) (як-є ())|(8 -2 1)"
                 "(список 4 4 4) (як-є ())|(5 5 5)"
                 "(список 1 2) (список 9 8)|(3 2 9 8)");;
    довжина-списку)
      # Унарна рекурсія не повинна програвати лише через інший інтерфейс.
      # Порівнюємо однакові вхідні списки, не фіксуючи кількість параметрів.
      if [[ "$final_call" =~ [[:space:]]0\)$ ]]; then
        witnesses=("(як-є ()) 0|0" "(список 1) 0|1" "(список 1 2 3) 0|3")
      else
        witnesses=("(як-є ())|0" "(список 1)|1" "(список 1 2 3)|3")
      fi;;
  esac
  witness_index=0
  for witness in "${witnesses[@]}"; do
    witness_index=$((witness_index + 1))
    witness_args="${witness%%|*}"
    witness_expected="${witness#*|}"
    witness_source="$tmp/вхід-$witness_index.lisp"
    witness_binary="$tmp/вхід-$witness_index.sens"
    {
      cat "$source"
      printf '\n(%s %s)\n' "$function_name" "$witness_args"
    } > "$witness_source"
    "$sens" --t5m-mint "$witness_source" "$witness_binary" >/dev/null ||
      error "SENS не закодував змінний вхід $path №$witness_index"
    "$trit" open "$witness_binary" > "$tmp/вхід-$witness_index" ||
      error "Zig не відкрив змінний вхід $path №$witness_index"
    "$trit" verify-view "$witness_binary" >/dev/null ||
      error "необоротний змінний вхід $path №$witness_index"
    "$sens" --t5m-pair "$witness_source" "$witness_binary" --core4-runtime > "$tmp/вхід-$witness_index.paired" ||
      error "не виконано парний змінний вхід $path №$witness_index"
    "$trit" eval-core4 "$witness_binary" > "$tmp/вхід-$witness_index.actual" ||
      error "не виконано автономний змінний вхід $path №$witness_index"
    printf '%s\n' "$witness_expected" > "$tmp/вхід-$witness_index.expected"
    cmp -s "$tmp/вхід-$witness_index.actual" "$tmp/вхід-$witness_index.expected" ||
      error "помилковий алгоритм $path на змінному вході №$witness_index: очікувано $witness_expected"
    cmp -s "$tmp/вхід-$witness_index.paired" "$tmp/вхід-$witness_index.actual" ||
      error "розходження SENS paired/standalone $path на змінному вході №$witness_index"
  done
  printf 'CONTEST_INPUT_WITNESSES_PASS path=%s cases=%s native=SENS_ZIG_T5M\n' "$path" "$witness_index"
  if [[ "${SENS_CONTEST_PROOF_ONLY:-false}" == true ]]; then
    printf 'CONTEST_PROOF_ONLY_PASS path=%s inputs=%s native=SENS_ZIG_T5M\n' "$path" "$witness_index"
  else
    bytes="$(wc -c < "$path")"
    rows+="$task"$'\t'"$bytes"$'\t'"$nodes"$'\t'"$visits"$'\t'"$path"$'\n'
    printf "CONTEST_EXECUTED_PASS path=%s T5M=%s AST=%s visits=%s result=%s\n" "$path" "$bytes" "$nodes" "$visits" "$result"
  fi
  rm -rf -- "$tmp"
  tmp=""
done
if [[ "${SENS_CONTEST_PROOF_ONLY:-false}" == true ]]; then
  printf "CONTEST_NATIVE_WITNESSES_PASS count=%s native=SENS_ZIG_T5M metrics=NOT_MEASURED\n" "${#seen[@]}"
else
  printf "\nЗадача | T5M байти | AST | visits | Файл\n"
  printf "%s" "$rows" | sort -t $'\t' -k1,1 -k2,2n -k3,3n -k4,4n
  printf "CONTEST_NATIVE_PASS count=%s\n" "${#seen[@]}"
fi
printf "CONTEST_PENDING_NATIVE_PAIR_COUNT count=%s status=NOT_EXECUTED\n" "$pending_native_pair"
