#!/usr/bin/env python3
"""#2664 lane C — anti-numerology theorem for the 44 PURE-UNKNOWN D6 slots.

Research only.  This proves a negative result:

    coordinate labels alone cannot select a canonical D6 resident

when every PURE-UNKNOWN slot has the same admitted evidence and class-preserving
relabelings are allowed.

No new canonical occupancy, width, resident, or owner decision is made here.
The already owner-ratified 001111 resident is treated as fixed external evidence.
"""

from __future__ import annotations

import argparse
import json
import math
import runpy
from pathlib import Path
from typing import Any, Callable

REPO = Path(__file__).resolve().parents[2]
FRONTIER = REPO / "benchmarks" / "d6-unknown-frontier" / "run.py"
TARGET = "001111"


def hamming(a: str, b: str) -> int:
    assert len(a) == len(b)
    return sum(x != y for x, y in zip(a, b))


def common_prefix(a: str, b: str) -> int:
    n = 0
    for x, y in zip(a, b):
        if x != y:
            break
        n += 1
    return n


def evidence_signature(row: dict[str, Any]) -> tuple[Any, ...]:
    """Everything admitted about a PURE-UNKNOWN row except its coordinate label."""
    return (
        row["canonical_status"],
        row["canonical_semantic_member"],
        row["canonical_placement_ref"],
        row["research_evidence_class"],
        tuple(row["research_refs"]),
        row["note"],
    )


def winner(
    labels_by_slot: dict[str, str],
    score: Callable[[str], tuple[int, ...]],
) -> str:
    return min(labels_by_slot, key=lambda slot: score(labels_by_slot[slot]))


def swap_labels(labels_by_slot: dict[str, str], a: str, b: str) -> dict[str, str]:
    out = dict(labels_by_slot)
    out[a], out[b] = out[b], out[a]
    return out


def build() -> dict[str, Any]:
    ns = runpy.run_path(str(FRONTIER))
    frontier_result = ns["build"]()
    rows = frontier_result["frontier"]

    pure_rows = [
        row for row in rows
        if row["research_evidence_class"] == ns["PURE_UNKNOWN"]
    ]
    nonpure_rows = [
        row for row in rows
        if row["research_evidence_class"] != ns["PURE_UNKNOWN"]
    ]

    assert len(pure_rows) == 44
    assert len(nonpure_rows) == 3
    assert frontier_result["canonical"]["ratified_manual_coordinates"] == [TARGET]
    assert frontier_result["canonical"]["research_occupancy_mutations"] == 0

    # All 44 slots carry exactly the same admitted evidence.
    signatures = {evidence_signature(row) for row in pure_rows}
    assert len(signatures) == 1

    # Stable abstract slot ids let us distinguish evidence identity from the
    # arbitrary 6-bit label currently printed on that slot.
    sorted_pure = sorted(pure_rows, key=lambda row: row["coordinate"])
    labels_by_slot = {
        f"slot-{index:02d}": row["coordinate"]
        for index, row in enumerate(sorted_pure)
    }
    assert len(set(labels_by_slot.values())) == 44

    # Every transposition between PURE-UNKNOWN labels is class preserving:
    # all non-PURE evidence rows remain fixed and all swapped slots retain the
    # same evidence signature.  S_44 is generated by transpositions.
    slots = sorted(labels_by_slot)
    transposition_count = 0
    for i, left in enumerate(slots):
        for right in slots[i + 1:]:
            swapped = swap_labels(labels_by_slot, left, right)
            assert set(swapped.values()) == set(labels_by_slot.values())
            assert all(
                evidence_signature(sorted_pure[int(slot.split("-")[1])])
                == next(iter(signatures))
                for slot in (left, right)
            )
            transposition_count += 1

    assert transposition_count == math.comb(44, 2) == 946

    closure = ns["load_closure"]()
    generated = sorted(
        row["coordinate"] for row in closure if row["status"] == "generated"
    )
    assert len(generated) == 16

    def numeric(coord: str) -> tuple[int, ...]:
        return (int(coord, 2),)

    def hamming_weight(coord: str) -> tuple[int, ...]:
        return (coord.count("1"), int(coord, 2))

    def owner_distance(coord: str) -> tuple[int, ...]:
        return (hamming(coord, TARGET), int(coord, 2))

    def owner_prefix(coord: str) -> tuple[int, ...]:
        return (-common_prefix(coord, TARGET), int(coord, 2))

    def generated_distance(coord: str) -> tuple[int, ...]:
        return (
            min(hamming(coord, resident) for resident in generated),
            int(coord, 2),
        )

    rankings: dict[str, Callable[[str], tuple[int, ...]]] = {
        "numeric-min": numeric,
        "hamming-weight-then-numeric": hamming_weight,
        "hamming-distance-to-001111": owner_distance,
        "prefix-proximity-to-001111": owner_prefix,
        "hamming-distance-to-generated-set": generated_distance,
    }

    ranking_results = []
    for name, score in rankings.items():
        before = winner(labels_by_slot, score)
        before_label = labels_by_slot[before]

        # Swap the winning label with any other evidence-identical slot.
        other = next(slot for slot in slots if slot != before)
        relabeled = swap_labels(labels_by_slot, before, other)
        after = winner(relabeled, score)
        after_label = relabeled[after]

        assert after != before
        assert after == other
        assert after_label == before_label

        ranking_results.append(
            {
                "ranking": name,
                "winner_slot_before": before,
                "winner_coordinate_label": before_label,
                "swap_with_slot": other,
                "winner_slot_after_relabeling": after,
                "same_best_label_after_relabeling": after_label,
                "semantic_evidence_changed": False,
                "canonical_occupancy_changed": False,
                "verdict": "REJECT-COORDINATE-LABEL-AUTHORITY",
            }
        )

    # Group-theoretic consequence: the action on PURE-UNKNOWN is transitive.
    # A subset fixed by every permutation of a transitive full symmetric action
    # is either empty or the entire orbit.  Therefore no evidence-invariant
    # singleton candidate exists.
    result = {
        "schema": "d6-pure-unknown-antinumerology/v1",
        "issue": 2664,
        "domain": "Core D6",
        "phase": "SENS-DERIVATION",
        "pure_unknown_count": 44,
        "evidence_signature_count": len(signatures),
        "class_preserving_transpositions": transposition_count,
        "orbit_size": 44,
        "group_action": "full symmetric relabeling on evidence-identical PURE-UNKNOWN slots",
        "invariant_subset_theorem": {
            "fixed_subsets": ["EMPTY", "ALL-44-PURE-UNKNOWN"],
            "invariant_singleton_exists": False,
        },
        "coordinate_only_rankings": ranking_results,
        "fixed_nonpure_unknown_coordinates": sorted(row["coordinate"] for row in nonpure_rows),
        "fixed_owner_ratified_coordinates": [TARGET],
        "canonical": {
            "generated_members": frontier_result["canonical"]["generated_members"],
            "ratified_manual_residents": frontier_result["canonical"]["ratified_manual_residents"],
            "unknown_free": frontier_result["canonical"]["unknown_free"],
            "research_occupancy_mutations": 0,
        },
        "result": "NO-CANDIDATE-FROM-COORDINATE-ONLY",
        "falsifier": (
            "produce a semantic/evidence property independent of coordinate labels "
            "that breaks the 44-slot relabeling orbit"
        ),
        "guards": [
            "numeric adjacency is not semantic evidence",
            "Hamming distance is not semantic evidence",
            "prefix proximity is not semantic evidence",
            "001111 owner evidence does not transfer to PURE-UNKNOWN slots",
            "no coordinate allocation",
        ],
    }
    return result


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()

    result = build()
    rendered = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(rendered, encoding="utf-8")

    print("D6-PURE-UNKNOWN-ANTI-NUMEROLOGY=PASS")
    print("pure-unknown=44")
    print("evidence-signatures=1")
    print("class-preserving-transpositions=946")
    print("orbit-size=44")
    print("invariant-singleton=false")
    print("coordinate-only-rankings-rejected=5")
    print("research-occupancy-mutations=0")
    print("RESULT=NO-CANDIDATE-FROM-COORDINATE-ONLY")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
