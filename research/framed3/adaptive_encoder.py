"""Дослідний адаптивний фізичний енкодер SENS, без зміни канонічного T5.

Точні двійкові слова зберігаються буквально. Немає семантичних таблиць,
перенумерації доменів або автоматичної зміни читача .sens.

Два експериментальні профілі утворюють окремий носій .senc:
  F3 + Рамка-3; F4 + Tb-33. Перший байт обох профілів є недійсним
  байтом T5 (основа 3, 5 тритів на байт: 0..242), тож помилка маршруту
  не призведе до непомітного успіху канонічного T5-декодера.
"""

from dataclasses import dataclass

from research_codec import FrameError, decode as декодувати_рамку, encode as кодувати_рамку
from tb33_tail_research import TailError, decode as декодувати_тб33, encode as кодувати_тб33


МІТКА_РАМКА = 0xF3
МІТКА_ТБ33 = 0xF4
ОСНОВА = 3
ТРИТОВ_У_БАЙТІ = 5


class ПомилкаНосія(ValueError):
    """Формат, довжина або відновлення точних слів не відповідають контракту."""


@dataclass(frozen=True)
class Носій:
    профіль: str
    дані: bytes
    розширення: str


def перевірити_слова(слова):
    результат = tuple(слова)
    for слово in результат:
        if not isinstance(слово, str) or not 1 <= len(слово) <= 9 or any(біт not in "01" for біт in слово):
            raise ПомилкаНосія("лише точні слова D1–D9 із бітів 0/1")
    return результат


def трити(слова):
    return tuple(int(трит) for трит in "2".join(слова))


def кодувати_т5(слова):
    слова = перевірити_слова(слова)
    потік = трити(слова)
    потік += (2,) * (-len(потік) % ТРИТОВ_У_БАЙТІ)
    return bytes(
        sum(потік[початок + i] * ОСНОВА ** (4 - i) for i in range(5))
        for початок in range(0, len(потік), 5)
    )


def декодувати_т5(дані):
    if not isinstance(дані, bytes):
        raise ПомилкаНосія("T5 повинен одержати bytes")
    цифри = []
    for байт in дані:
        if байт >= 243:
            raise ПомилкаНосія("недійсний байт T5")
        трійки = []
        for i in range(5):
            трійки.append((байт // (3 ** (4 - i))) % 3)
        цифри.extend(трійки)
    while цифри and цифри[-1] == 2:
        цифри.pop()
    сирі = "".join(str(цифра) for цифра in цифри)
    слова = tuple(сирі.split("2")) if сирі else ()
    перевірити_слова(слова)
    if кодувати_т5(слова) != дані:
        raise ПомилкаНосія("неканонічне доповнення T5")
    return слова


def найменший_носій(слова):
    """Мінімум фізичних байтів серед трьох наявних дослідних маршрутів.

    Повертає T5 без заголовка (.sens) або саморозрізнюваний .senc
    з 1-байтовою міткою. За рівності перемагає канонічний T5.
    Це НЕ доказ глобальної оптимальності всіх можливих кодеків.
    """
    слова = перевірити_слова(слова)
    переможець = Носій("т5", кодувати_т5(слова), ".sens")
    try:
        кадр = bytes((МІТКА_РАМКА,)) + кодувати_рамку(слова)
        if len(кадр) < len(переможець.дані):
            переможець = Носій("рамка3", кадр, ".senc")
    except FrameError:
        pass  # Поза доведеним підкласом однієї зовнішньої D2-рамки.
    трицифри = трити(слова)
    try:
        кадр = bytes((МІТКА_ТБ33,)) + кодувати_тб33(трицифри)
        if len(кадр) < len(переможець.дані):
            переможець = Носій("тб33", кадр, ".senc")
    except TailError:
        pass  # Поза класом без 22 з кінцевим D2:01.
    if прочитати_носій(переможець) != слова:
        raise ПомилкаНосія("немає точного зворотного перетворення")
    return переможець


def прочитати_носій(носій):
    """Маршрут визначений розширенням плюс перевіреною міткою, не евристикою."""
    if not isinstance(носій, Носій) or not isinstance(носій.дані, bytes):
        raise ПомилкаНосія("очікується точний носій з bytes")
    if носій.профіль == "т5" and носій.розширення == ".sens":
        return декодувати_т5(носій.дані)
    if носій.розширення != ".senc" or not носій.дані:
        raise ПомилкаНосія("невідома пара формату й розширення")
    мітка, тіло = носій.дані[0], носій.дані[1:]
    try:
        if носій.профіль == "рамка3" and мітка == МІТКА_РАМКА:
            слова = декодувати_рамку(тіло)
            if bytes((мітка,)) + кодувати_рамку(слова) == носій.дані:
                return слова
        if носій.профіль == "тб33" and мітка == МІТКА_ТБ33:
            трицифри = декодувати_тб33(тіло)
            сирі = "".join(str(x) for x in трицифри)
            слова = перевірити_слова(tuple(сирі.split("2")))
            if bytes((мітка,)) + кодувати_тб33(трити(слова)) == носій.дані:
                return слова
    except (FrameError, TailError) as помилка:
        raise ПомилкаНосія("недійсний код дослідного профілю") from помилка
    raise ПомилкаНосія("невідома мітка або неканонічний потік")


if __name__ == "__main__":
    зразки = {
        "порожня D2-структура": ("10", "01"),
        "цитування": ("10", "001", "00", "000", "01"),
        "вкладена структура": tuple("10 100 00 10 111 00 1 00 0 01 01".split()),
    }
    for назва, слова in зразки.items():
        вибір = найменший_носій(слова)
        print(f"{назва}: T5={len(кодувати_т5(слова))}, обрано={len(вибір.дані)} байтів, {вибір.профіль} {вибір.розширення}")
