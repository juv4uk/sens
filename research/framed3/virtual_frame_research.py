"""Дослід: універсальне блокове розширення принципу «Рамка-3».

НЕ є production-кодеком SENS, канонічним читачем чи затвердженим .senc.
Це оборотний контейнер точних слів D1–D9, з окремими режимами:
  0: справжня одиночна D2-рамка (чинний F3 research);
  1: *віртуальні* приклеєні крайні 10/01, які декодер прибирає.
Синтетичні краї ніколи не змінюють вихідні слова.
Для довгих даних застосовуються незалежно ранжовані блоки до 128 тритів.
"""

from __future__ import annotations

from collections.abc import Iterable

import research_codec as рамка

МАГІЯ = bytes((0xFF, 0x33, 0x01))
МЕЖА = 128
МАКС_СЛІВ = 100_000
МАКС_БАЙТІВ = 2_000_000
РЕЖИМ_ПРЯМИЙ = 0
РЕЖИМ_ВІРТУАЛЬНИЙ = 1
КІНЕЦЬ = 0xFF


class ПомилкаРамки(ValueError):
    """Недопущений потік, неканонічне кодування або вихід за межі."""


def _слова(вхід: Iterable[str]) -> tuple[str, ...]:
    результат = tuple(вхід)
    if len(результат) > МАКС_СЛІВ:
        raise ПомилкаРамки("надмірна кількість слів")
    for слово in результат:
        if (not isinstance(слово, str) or not 1 <= len(слово) <= 9
                or any(біт not in "01" for біт in слово)):
            raise ПомилкаРамки("лише точні непорожні двійкові слова D1–D9")
    return результат


def _довжина(число: int) -> bytes:
    if not 0 <= число <= МАКС_БАЙТІВ:
        raise ПомилкаРамки("недопустима довжина")
    результат = bytearray()
    while True:
        частина = число & 0x7F
        число >>= 7
        результат.append(частина | (0x80 if число else 0))
        if not число:
            return bytes(результат)


def _читати_довжину(байти: bytes, позиція: int) -> tuple[int, int]:
    початок = позиція
    число = 0
    for зсув in range(0, 35, 7):
        if позиція >= len(байти):
            raise ПомилкаРамки("обірвана довжина блока")
        б = байти[позиція]
        позиція += 1
        число |= (б & 0x7F) << зсув
        if not (б & 0x80):
            if число > МАКС_БАЙТІВ or байти[початок:позиція] != _довжина(число):
                raise ПомилкаРамки("надмірна або неканонічна довжина")
            return число, позиція
    raise ПомилкаРамки("переповнений префікс довжини")


def _байти_за_тритами(трити: tuple[int, ...]) -> bytes:
    """Використовує лише rank/capacity дослідної Рамки-3 (не її D2-парсер)."""
    n = len(трити)
    if not 4 <= n <= МЕЖА:
        raise ПомилкаРамки("довжина рамки не підтримується")
    номер = рамка._rank(трити)
    for ширина, початок, кінець in рамка._buckets():
        if початок <= n <= кінець:
            поправка = sum(рамка.capacity(k) for k in range(початок, n))
            return (поправка + номер).to_bytes(ширина, "big")
    raise ПомилкаРамки("немає бакета для рамки")


def _трити_за_байтами(байти: bytes) -> tuple[int, ...]:
    for ширина, початок, кінець in рамка._buckets():
        if len(байти) != ширина:
            continue
        номер = int.from_bytes(байти, "big")
        for n in range(початок, кінець + 1):
            місткість = рамка.capacity(n)
            if номер < місткість:
                трити = рамка._unrank(n, номер)
                if _байти_за_тритами(трити) != байти:
                    raise ПомилкаРамки("неканонічне ранжування")
                return трити
            номер -= місткість
        raise ПомилкаРамки("невикористаний фізичний код")
    raise ПомилкаРамки("довжина фізичного блока не підтримується")


def _віртуальні_трити(слова: tuple[str, ...]) -> tuple[int, ...]:
    середина = "2".join(слова)
    текст = "10" + середина + "01"
    if len(текст) > МЕЖА:
        raise ПомилкаРамки("надто довгий блок")
    return tuple(int(цифра) for цифра in текст)


def _читати_віртуальні(байти: bytes) -> tuple[str, ...]:
    трити = _трити_за_байтами(байти)
    if трити[:2] != (1, 0) or трити[-2:] != (0, 1):
        raise ПомилкаРамки("пошкоджено синтетичні краї")
    середина = "".join(str(t) for t in трити[2:-2])
    слова = _слова(середина.split("2") if середина else ())
    if _віртуальні_трити(слова) != трити:
        raise ПомилкаРамки("розбіжність меж слів")
    return слова


def _частини(слова: tuple[str, ...]) -> list[tuple[str, ...]]:
    if not слова:
        return [()]
    частини = []
    i = 0
    while i < len(слова):
        j, n = i, 4  # Приклеєні зовнішні D2 10/01 не входять у вихідні слова.
        while j < len(слова):
            додаток = len(слова[j]) + int(j > i)
            if n + додаток > МЕЖА:
                break
            n += додаток
            j += 1
        if j == i:
            raise ПомилкаРамки("слово не поміщається у блок")
        частини.append(слова[i:j])
        i = j
    return частини


def кодувати(вхід: Iterable[str]) -> bytes:
    """Оборотна побайтова дослідна оболонка, НЕ production .sens."""
    слова = _слова(вхід)
    запис = bytearray(МАГІЯ)
    try:
        прямий = рамка.encode(слова)
    except рамка.FrameError:
        прямий = None

    if прямий is not None:
        запис.append(РЕЖИМ_ПРЯМИЙ)
        запис.extend(_довжина(len(прямий)))
        запис.extend(прямий)
    else:
        for частина in _частини(слова):
            тіло = _байти_за_тритами(_віртуальні_трити(частина))
            запис.append(РЕЖИМ_ВІРТУАЛЬНИЙ)
            запис.extend(_довжина(len(тіло)))
            запис.extend(тіло)
    запис.append(КІНЕЦЬ)
    if len(запис) > МАКС_БАЙТІВ:
        raise ПомилкаРамки("надмірний фізичний запис")
    return bytes(запис)


def декодувати(байти: bytes) -> tuple[str, ...]:
    if not isinstance(байти, bytes) or len(байти) > МАКС_БАЙТІВ:
        raise ПомилкаРамки("недопустимий фізичний запис")
    if not байти.startswith(МАГІЯ):
        raise ПомилкаРамки("невідома рамка або версія")
    позиція = len(МАГІЯ)
    слова = []
    режими = []
    while True:
        if позиція >= len(байти):
            raise ПомилкаРамки("немає термінатора запису")
        режим = байти[позиція]
        позиція += 1
        if режим == КІНЕЦЬ:
            break
        if режим not in (РЕЖИМ_ПРЯМИЙ, РЕЖИМ_ВІРТУАЛЬНИЙ):
            raise ПомилкаРамки("невідомий режим")
        розмір, позиція = _читати_довжину(байти, позиція)
        if розмір == 0 or позиція + розмір > len(байти):
            raise ПомилкаРамки("обірване або порожнє тіло")
        тіло = байти[позиція:позиція + розмір]
        позиція += розмір
        if режим == РЕЖИМ_ПРЯМИЙ:
            if режими:
                raise ПомилкаРамки("пряма рамка не може входити в серію")
            try:
                відновлені = рамка.decode(тіло)
            except рамка.FrameError as err:
                raise ПомилкаРамки("пошкоджена пряма D2-рамка") from err
        else:
            відновлені = _читати_віртуальні(тіло)
        слова.extend(відновлені)
        if len(слова) > МАКС_СЛІВ:
            raise ПомилкаРамки("надто багато вихідних слів")
        режими.append(режим)
    if позиція != len(байти) or not режими:
        raise ПомилкаРамки("сміття після кінця або відсутнє тіло")
    результат = tuple(слова)
    # Заборонено надлишкові розбиття, режимні alias і довгі varint-и.
    if кодувати(результат) != байти:
        raise ПомилкаРамки("неоднозначний / неканонічний фізичний запис")
    return результат
