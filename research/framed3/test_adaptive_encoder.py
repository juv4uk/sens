"""Позитивні й негативні докази дослідного адаптивного носія."""

import dataclasses
import itertools
import unittest

from adaptive_encoder import (
    МІТКА_РАМКА, МІТКА_ТБ33, Носій, ПомилкаНосія, декодувати_т5,
    кодувати_т5, найменший_носій, прочитати_носій,
)


class АдаптивнийЕнкодерТест(unittest.TestCase):
    def test_короткі_структури_з_урахуванням_мітки(self):
        зразки = [
            (("10", "01"), 1, 1, "т5"),
            (("10", "001", "00", "000", "01"), 4, 3, "рамка3"),
            (tuple("10 100 00 10 111 00 1 00 0 01 01".split()), 7, 6, "рамка3"),
        ]
        for слова, довжина_т5, довжина_вибору, профіль in зразки:
            with self.subTest(слова=слова):
                self.assertEqual(len(кодувати_т5(слова)), довжина_т5)
                переможець = найменший_носій(слова)
                self.assertEqual((переможець.профіль, len(переможець.дані)), (профіль, довжина_вибору))
                self.assertEqual(прочитати_носій(переможець), слова)

    def test_т5_усі_домени_і_початкові_нулі(self):
        зразки = ["0", "00", "000", "0000", "00000", "000000", "0000000", "00000000", "000000000"]
        self.assertEqual(декодувати_т5(кодувати_т5(зразки)), tuple(зразки))
        for n in range(1, 6):
            for слова in itertools.product(("0", "1", "00", "01", "10", "11"), repeat=n):
                raw = кодувати_т5(слова)
                self.assertEqual(декодувати_т5(raw), слова)

    def test_багато_форм_не_можна_підміняти_рамкою(self):
        слова = ("10", "01", "10", "01")
        обраний = найменший_носій(слова)
        self.assertEqual(прочитати_носій(обраний), слова)
        self.assertNotEqual(обраний.профіль, "рамка3")

    def test_довгий_потік_і_тб33(self):
        слова = ("10",) + ("00010101",) * 48 + ("01",)
        обраний = найменший_носій(слова)
        self.assertEqual(обраний.профіль, "тб33")
        self.assertLess(len(обраний.дані), len(кодувати_т5(слова)))
        self.assertEqual(прочитати_носій(обраний), слова)
        self.assertEqual(обраний.дані[0], МІТКА_ТБ33)

    def test_мітки_не_є_допустимими_байтами_т5(self):
        for мітка in (МІТКА_РАМКА, МІТКА_ТБ33):
            self.assertGreaterEqual(мітка, 243)
            with self.assertRaises(ПомилкаНосія):
                декодувати_т5(bytes((мітка, 0)))

    def test_пошкоджена_або_невідома_рамка_fail_closed(self):
        вибір = найменший_носій(("10", "001", "00", "000", "01"))
        for пошкоджений in (
            dataclasses.replace(вибір, розширення=".sens"),
            dataclasses.replace(вибір, профіль="тб33"),
            dataclasses.replace(вибір, дані=b""),
            dataclasses.replace(вибір, дані=b"\xff" + вибір.дані[1:]),
        ):
            with self.subTest(пошкоджений=пошкоджений):
                with self.assertRaises(ПомилкаНосія):
                    прочитати_носій(пошкоджений)
        with self.assertRaises(ПомилкаНосія):
            декодувати_т5(b"\xf2")  # Лише доповнення, неканонічна порожня програма.

    def test_детермінованість_і_відсутність_другого_маршруту(self):
        слова = tuple("10 100 00 10 111 00 1 00 0 01 01".split())
        a = найменший_носій(слова)
        b = найменший_носій(слова)
        self.assertEqual(a, b)
        self.assertEqual(прочитати_носій(a), слова)


if __name__ == "__main__":
    unittest.main()
