#!/usr/bin/env python3
"""Рамка-3: дослідне оборотне пакування ОДНІЄЇ зовнішньої D2-форми.

Не є форматом .sens. Не змінює T5, домени або семантику.
Ранжує транспортні трити без «22», з відомими краями 10 / 01.
Довжину визначає кількість фізичних байтів та діапазон рангу.
"""
from functools import lru_cache

ПОЧАТОК = (1, 0, 2)
КІНЕЦЬ = (2, 0, 1)
МЕЖА_БАЙТІВ = 8


def дозволені(довжина, місце):
    if місце < 3:
        return (ПОЧАТОК[місце],)
    if місце >= довжина - 3:
        return (КІНЕЦЬ[місце - (довжина - 3)],)
    return (0, 1, 2)


@lru_cache(None)
def продовжень(довжина, місце, попередній):
    if місце == довжина:
        return 1
    return sum(продовжень(довжина, місце + 1, цифра)
               for цифра in дозволені(довжина, місце)
               if not (попередній == цифра == 2))


@lru_cache(None)
def місткість(довжина):
    if довжина == 5:
        return 1  # Єдина рамка 10 2 01.
    if довжина < 7:
        return 0
    return продовжень(довжина, 0, -1)


@lru_cache(None)
def групи():
    """(байти, перша_довжина, остання_довжина, загальна_місткість)."""
    результат = []
    перша = 5
    for байтів in range(1, МЕЖА_БАЙТІВ + 1):
        сума = 0
        остання = перша - 1
        while сума + місткість(остання + 1) <= (1 << (8 * байтів)):
            остання += 1
            сума += місткість(остання)
        if остання < перша:
            raise ValueError("Жодна довжина не вмістилася")
        результат.append((байтів, перша, остання, сума))
        перша = остання + 1
    return tuple(результат)


def ранг(трити):
    довжина = len(трити)
    if довжина == 5:
        if трити != (1, 0, 2, 0, 1):
            raise ValueError("Недопустима порожня рамка")
        return 0
    if not місткість(довжина):
        raise ValueError("Недопустима довжина")
    число = 0
    попередній = -1
    for місце, цифра in enumerate(трити):
        if цифра not in дозволені(довжина, місце) or цифра == попередній == 2:
            raise ValueError("Недопустима рамка або «22»")
        for кандидат in дозволені(довжина, місце):
            if кандидат == попередній == 2:
                continue
            if кандидат == цифра:
                break
            число += продовжень(довжина, місце + 1, кандидат)
        попередній = цифра
    return число


def за_рангом(довжина, число):
    if not (0 <= число < місткість(довжина)):
        raise ValueError("Ранг поза межами")
    if довжина == 5:
        return (1, 0, 2, 0, 1)
    трити = []
    попередній = -1
    for місце in range(довжина):
        for цифра in дозволені(довжина, місце):
            if цифра == попередній == 2:
                continue
            скільки = продовжень(довжина, місце + 1, цифра)
            if число < скільки:
                трити.append(цифра)
                попередній = цифра
                break
            число -= скільки
        else:
            raise AssertionError("Внутрішня помилка зворотного ранжування")
    return tuple(трити)


def трити_форми(слова):
    """Провірка фізичної рамки, НЕ повна граматика D2."""
    if len(слова) < 2 or слова[0] != "10" or слова[-1] != "01":
        raise ValueError("Вимагається одна зовнішня рамка 10 ... 01")
    вкладеність = 0
    for номер, слово in enumerate(слова):
        if not (1 <= len(слово) <= 9) or any(біт not in "01" for біт in слово):
            raise ValueError("Неточне слово D1–D9")
        if слово == "10":
            вкладеність += 1
        elif слово == "01":
            вкладеність -= 1
            if вкладеність < 0 or (вкладеність == 0 and номер != len(слова) - 1):
                raise ValueError("Зайве закриття або друга верхня форма")
        elif вкладеність <= 0:
            raise ValueError("Слово поза рамкою")
    if вкладеність:
        raise ValueError("Незакрита рамка")
    return tuple(int(т) for т in "2".join(слова))


def упакувати(слова):
    трити = трити_форми(слова)
    довжина = len(трити)
    for байтів, перша, остання, _ in групи():
        if перша <= довжина <= остання:
            число = sum(місткість(n) for n in range(перша, довжина)) + ранг(трити)
            if число >= (1 << (8 * байтів)):
                raise AssertionError("Переповнення фізичного блоку")
            return число.to_bytes(байтів, "big")
    raise ValueError("Перевищено межу дослідного носія")


def розпакувати(дані):
    група = next((г for г in групи() if г[0] == len(дані)), None)
    if група is None:
        raise ValueError("Недопустима фізична довжина")
    _, перша, остання, _ = група
    число = int.from_bytes(дані, "big")
    for довжина in range(перша, остання + 1):
        скільки = місткість(довжина)
        if число < скільки:
            трити = за_рангом(довжина, число)
            слова = "".join(map(str, трити)).split("2")
            if трити_форми(слова) != трити or упакувати(слова) != дані:
                raise ValueError("Неканонічний фізичний запис")
            return слова
        число -= скільки
    raise ValueError("Незайнятий фізичний код")


def байтів_т5(слова):
    return (len(трити_форми(слова)) + 4) // 5
